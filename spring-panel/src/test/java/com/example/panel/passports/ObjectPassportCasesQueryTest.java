package com.example.panel.passports;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.example.panel.support.PostgresqlJdbcTestSupport;
import java.sql.Connection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import javax.sql.DataSource;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.web.server.ResponseStatusException;

class ObjectPassportCasesQueryTest {

    @Test
    void loadsNormalizedPassportContextAndProjectsDeduplicatedCases() throws Exception {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplate("passport_cases_query");
        DataSource dataSource = jdbc.getDataSource();
        jdbc.execute("CREATE TABLE objects (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, address TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("CREATE TABLE object_passports (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, object_id BIGINT NOT NULL REFERENCES objects(id), passport_number TEXT, details TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("CREATE TABLE messages (group_msg_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id TEXT, user_id BIGINT DEFAULT 10, channel_id BIGINT DEFAULT 1, created_date TEXT, business TEXT, city TEXT, location_name TEXT, problem TEXT, created_at TIMESTAMPTZ)");

        jdbc.execute("CREATE TABLE tickets (user_id BIGINT, ticket_id TEXT, channel_id BIGINT, created_at TIMESTAMPTZ, ticket_public_id TEXT, is_general BOOLEAN DEFAULT FALSE, status TEXT DEFAULT 'pending', PRIMARY KEY(user_id,ticket_id))");
        jdbc.update("INSERT INTO tickets(user_id,ticket_id,channel_id) VALUES (10,'T-1',1),(10,'T-2',1)");

        ObjectPassportPhotoModel photoModel = new ObjectPassportPhotoModel(name -> "/photos/" + name);
        ObjectPassportPayloadModel payloadModel = new ObjectPassportPayloadModel(photoModel);
        ObjectPassportPersistence persistence = new ObjectPassportPersistence(new ObjectMapper(), payloadModel);
        ObjectPassportAppealQuery appealQuery = new ObjectPassportAppealQuery(jdbc);
        ObjectPassportCasesQuery query = new ObjectPassportCasesQuery(persistence, payloadModel, appealQuery);

        long passportId;
        try (Connection connection = dataSource.getConnection()) {
            connection.setAutoCommit(false);
            Map<String, Object> payload = new LinkedHashMap<>();
            payload.put("business", "Business A");
            payload.put("city", "City A");
            payload.put("department", "Dept A");
            long objectId = persistence.insertObject(connection, payload);
            passportId = persistence.insertPassport(connection, objectId, payload);
            connection.commit();

            jdbc.update("INSERT INTO messages(ticket_id,business,city,location_name,problem,created_at) VALUES (?,?,?,?,?,?)", "T-1", "Business A", "City A", "Dept A", "older", "2026-09-16T10:00:00");
            jdbc.update("INSERT INTO messages(ticket_id,business,city,location_name,problem,created_at) VALUES (?,?,?,?,?,?)", "T-1", "Business A", "City A", "Dept A", "newer", "2026-09-16T11:00:00");
            jdbc.update("INSERT INTO messages(ticket_id,business,city,location_name,problem,created_at) VALUES (?,?,?,?,?,?)", "T-2", "Business A", "City A", "Dept A", "second", "2026-09-16T12:00:00");

            Map<String, Object> result = query.load(connection, passportId);
            assertThat(result)
                    .containsEntry("success", true)
                    .containsEntry("total_count", 2)
                    .containsEntry("total_minutes", 0)
                    .containsEntry("total_display", "0 мин");

            Object rawItems = result.get("items");
            assertThat(rawItems).isInstanceOf(List.class);
            List<?> items = (List<?>) rawItems;
            assertThat(items).hasSize(2);
            assertThat(((Map<?, ?>) items.get(0)).get("ticket_id")).isEqualTo("T-2");
            assertThat(((Map<?, ?>) items.get(1)).get("ticket_id")).isEqualTo("T-1");
            assertThat(((Map<?, ?>) items.get(1)).get("problem")).isEqualTo("newer");
            assertThat(((Map<?, ?>) items.get(0)).get("request_number")).isEqualTo("20260916-002");
            assertThat(((Map<?, ?>) items.get(1)).get("request_number")).isEqualTo("20260916-001");
            assertThat(((Map<?, ?>) items.get(0)).get("dialog_url")).isEqualTo("/dialogs?ticketId=T-2&channelId=1");
            String capture = System.getProperty("iguana.ui.capture");
            if (capture != null) {
                var destination = java.nio.file.Path.of(capture, "passport-cases.json");
                java.nio.file.Files.createDirectories(destination.getParent());
                new ObjectMapper().writeValue(destination.toFile(), result);
            }


            assertThatThrownBy(() -> query.load(connection, passportId + 1000))
                    .isInstanceOf(ResponseStatusException.class)
                    .satisfies(error -> assertThat(((ResponseStatusException) error).getStatusCode())
                            .isEqualTo(HttpStatus.NOT_FOUND));
        }
    }
}
