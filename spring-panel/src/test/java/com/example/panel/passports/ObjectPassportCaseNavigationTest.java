package com.example.panel.passports;

import static org.assertj.core.api.Assertions.assertThat;

import com.example.panel.support.PostgresqlJdbcTestSupport;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

class ObjectPassportCaseNavigationTest {
    private JdbcTemplate database() {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplate("passport_navigation");
        jdbc.execute("CREATE TABLE tickets (user_id BIGINT, ticket_id TEXT, channel_id BIGINT, created_at TIMESTAMPTZ, ticket_public_id TEXT, is_general BOOLEAN DEFAULT FALSE, status TEXT DEFAULT 'pending', PRIMARY KEY(user_id,ticket_id))");
        jdbc.execute("CREATE TABLE messages (group_msg_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT, ticket_id TEXT, channel_id BIGINT, business TEXT, city TEXT, location_name TEXT, problem TEXT, created_at TIMESTAMPTZ, created_date TEXT)");
        return jdbc;
    }

    private void ticket(JdbcTemplate jdbc, long user, String id, Long channel, String location, String time) {
        jdbc.update("INSERT INTO tickets(user_id,ticket_id,channel_id,created_at) VALUES (?,?,?,?::timestamptz)", user, id, channel, time);
        jdbc.update("INSERT INTO messages(user_id,ticket_id,channel_id,business,city,location_name,problem,created_at) VALUES (?,?,?,'СушиВёсла','Москва',?,'Проверка',?::timestamptz)", user, id, channel, location, time);
    }

    private List<Map<String, Object>> cases(JdbcTemplate jdbc) {
        return new ObjectPassportAppealQuery(jdbc).loadCases(Map.of("business", "СушиВесла", "department", "Касса"));
    }

    @Test
    void numbersIncludeOtherLocationsAndUseFirstMessageRatherThanLastSnapshot() {
        JdbcTemplate jdbc = database();
        ticket(jdbc, 10, "earlier", 1L, "Другая касса", "2026-11-20T08:00:00Z");
        ticket(jdbc, 11, "a-first", 2L, "Касса", "2026-11-20T09:00:00Z");
        ticket(jdbc, 12, "b-second", 1L, "Касса", "2026-11-20T09:00:00Z");
        ticket(jdbc, 13, "yesterday", 1L, "Касса", "2026-11-19T09:00:00Z");
        jdbc.update("INSERT INTO messages(user_id,ticket_id,channel_id,business,location_name,problem,created_at) VALUES (11,'a-first',2,'СушиВёсла','Касса','Позднее описание','2026-11-21T09:00:00Z')");

        assertThat(cases(jdbc)).hasSize(3).satisfies(items -> {
            assertThat(items.get(0)).containsEntry("request_number", "20261120-002")
                    .containsEntry("problem", "Позднее описание")
                    .containsEntry("channel_id", 2L)
                    .containsEntry("dialog_url", "/dialogs?ticketId=a-first&channelId=2");
            assertThat(items.get(1)).containsEntry("request_number", "20261120-003");
            assertThat(items.get(2)).containsEntry("request_number", "20261119-001");
        });
    }

    @Test
    void legacyDateFormatsMatchDialogNumberingAndMissingMessageDateUsesTicketDate() {
        JdbcTemplate jdbc = database();
        ticket(jdbc, 10, "iso", 1L, "Касса", "2026-11-20T08:00:00Z");
        ticket(jdbc, 11, "legacy", 1L, "Касса", "2026-11-20T09:00:00Z");
        ticket(jdbc, 12, "compact", 1L, "Касса", "2026-11-20T10:00:00Z");
        jdbc.update("UPDATE messages SET created_date = CASE ticket_id WHEN 'iso' THEN '2026-11-20' WHEN 'legacy' THEN '20.11.2026' ELSE '20261120' END");
        jdbc.update("UPDATE messages SET created_at=NULL WHERE ticket_id='compact'");
        assertThat(cases(jdbc)).extracting(item -> item.get("request_number"))
                .containsExactly("20261120-002", "20261120-001", "20261120-003");
    }

    @Test
    void collidingLegacyIdsRemainSeparateAndDoNotGetUnsafeLinksOrNumbers() {
        JdbcTemplate jdbc = database();
        ticket(jdbc, 10, "same", 1L, "Касса", "2026-11-20T08:00:00Z");
        ticket(jdbc, 11, "same", 2L, "Касса", "2026-11-20T09:00:00Z");
        assertThat(cases(jdbc)).hasSize(2).allSatisfy(item -> assertThat(item)
                .containsEntry("dialog_url", null).containsEntry("request_number", null));
    }

    @Test
    void mismatchedMessageOwnerOrChannelCannotBorrowTicketIdentity() {
        JdbcTemplate jdbc = database();
        ticket(jdbc, 10, "original", 1L, "Касса", "2026-11-20T08:00:00Z");
        jdbc.update("UPDATE messages SET channel_id=2");
        assertThat(cases(jdbc)).singleElement().satisfies(item -> assertThat(item)
                .containsEntry("dialog_url", null).containsEntry("request_number", null));
        jdbc.update("UPDATE messages SET channel_id=1,user_id=11");
        assertThat(cases(jdbc)).singleElement().satisfies(item -> assertThat(item)
                .containsEntry("dialog_url", null).containsEntry("request_number", null));
    }

    @Test
    void missingTicketIsVisibleWithoutFabricatedNumberOrLink() {
        JdbcTemplate jdbc = database();
        ticket(jdbc, 10, "orphan", 1L, "Касса", "2026-11-20T08:00:00Z");
        jdbc.update("DELETE FROM tickets");
        assertThat(cases(jdbc)).singleElement().satisfies(item -> assertThat(item)
                .containsEntry("ticket_id", "orphan").containsEntry("dialog_url", null)
                .containsEntry("request_number", null));
    }

    @Test
    void generalTicketUsesCanonicalPageWithoutLegacyRoute() {
        JdbcTemplate jdbc = database();
        ticket(jdbc, 10, "general", 1L, "Касса", "2026-11-20T08:00:00Z");
        jdbc.update("UPDATE tickets SET is_general=TRUE,ticket_public_id='1234567890abcdef1234567890abcdef'");
        assertThat(cases(jdbc)).singleElement().satisfies(item -> assertThat(item)
                .containsEntry("dialog_url", "/general-dialog-work/1234567890abcdef1234567890abcdef"));
        jdbc.update("UPDATE tickets SET ticket_public_id='invalid'");
        assertThat(cases(jdbc)).singleElement().satisfies(item -> assertThat(item).containsEntry("dialog_url", null));
    }

    @Test
    void urlEncodesTicketIdAndOmitsAbsentChannel() {
        JdbcTemplate jdbc = database();
        ticket(jdbc, 10, "x&channelId=99#<test>", null, "Касса", "2026-11-20T08:00:00Z");
        assertThat(cases(jdbc)).singleElement().satisfies(item -> assertThat(item)
                .containsEntry("dialog_url", "/dialogs?ticketId=x%26channelId%3D99%23%3Ctest%3E"));
    }

    @Test
    void emptyLocationReturnsNoCases() {
        assertThat(new ObjectPassportAppealQuery(database()).loadCases(Map.of())).isEmpty();
    }
}
