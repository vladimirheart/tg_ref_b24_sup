/** Real PostgreSQL, login/session/CSRF, preferences and parameter API; no working environment. */
@SpringBootTest(classes=PreferenceIdentityWebMvcTest.Application.class,
    properties={"spring.session.store-type=none","management.endpoint.health.group.readiness.include=ping"})
@AutoConfigureMockMvc
class PreferenceIdentityWebMvcTest {
    private static final String TYPE="ui_preferences.account.v2", PASSWORD="fixture preferences";
    private static final String HASH=new LegacyCompatiblePasswordEncoder().encode(PASSWORD);
    @Autowired MockMvc mvc;
    @Autowired JdbcTemplate jdbc;
    @Autowired SharedConfigService shared;
    @Autowired ProfileApiController profile;
    @Autowired GlobalModelAttributes modelAttributes;

    @Configuration(proxyBeanMethods=false)
    @EnableAutoConfiguration(exclude={DataSourceAutoConfiguration.class,FlywayAutoConfiguration.class})
    @Import({SecurityConfig.class,SecurityHeadersFilter.class,MvcConfig.class,RestExceptionHandler.class,
        ProfileApiController.class,DialogTriagePreferencesController.class,SettingsParametersController.class,
        UiPreferenceService.class,DialogTriagePreferenceService.class,SettingsParameterService.class,
        GlobalModelAttributes.class,Page.class})
    static class Application {
        @Bean(name="usersJdbcTemplate") JdbcTemplate jdbc(){
            var jdbc=PostgresqlJdbcTestSupport.freshJdbcTemplate("preference_identity");
            jdbc.execute("CREATE TABLE roles(id BIGINT PRIMARY KEY,name TEXT,permissions TEXT)");
            jdbc.execute("CREATE TABLE users(id BIGINT PRIMARY KEY,username TEXT UNIQUE,password TEXT,enabled BOOLEAN DEFAULT TRUE,is_blocked BOOLEAN DEFAULT FALSE,role_id BIGINT)");
            jdbc.execute("CREATE TABLE user_authorities(user_id BIGINT,authority TEXT)");
            jdbc.execute("CREATE TABLE settings_parameters(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,param_type TEXT,value TEXT,state TEXT,is_deleted BOOLEAN DEFAULT FALSE,deleted_at TIMESTAMP,extra_json TEXT)");
            return jdbc;
        }
        @Bean SharedConfigService shared(){return mock(SharedConfigService.class);}
        @Bean DialogAuditService audit(){return mock(DialogAuditService.class);}
        @Bean SettingsCatalogService catalog(){
            var catalog=mock(SettingsCatalogService.class);
            when(catalog.getParameterTypes()).thenReturn(Map.of(TYPE,"Internal","ui_preferences.v1","Legacy","role","Role"));
            when(catalog.getParameterDependencies()).thenReturn(Map.of());return catalog;
        }
    }
    @Controller static class Page {@GetMapping("/fixture-preferences") String page(){return "auth/login";}}
    @BeforeEach void setup(){
        jdbc.execute("TRUNCATE users,user_authorities,roles,settings_parameters");
        reset(shared);when(shared.loadSettings()).thenReturn(Map.of());
    }
    private void account(long id,String name){
        jdbc.update("INSERT INTO users(id,username,password) VALUES(?,?,?)",id,name,HASH);
        for(var authority:List.of("ROLE_USER","PAGE_SETTINGS"))jdbc.update("INSERT INTO user_authorities(user_id,authority) VALUES(?,?)",id,authority);
    }
    private long seed(String type,String key,String json){
        return jdbc.queryForObject("INSERT INTO settings_parameters(param_type,value,extra_json,is_deleted) VALUES(?,?,?,FALSE) RETURNING id",Long.class,type,key,json);
    }
    private Cookie tokenCookie(MvcResult page){var cookie=page.getResponse().getCookie("XSRF-TOKEN");assertThat(cookie).isNotNull();return cookie;}
    private String token(MvcResult page) throws Exception {
        var matcher=Pattern.compile("name=\"_csrf\"[^>]*value=\"([^\"]+)\"").matcher(page.getResponse().getContentAsString());
        assertThat(matcher.find()).isTrue();return matcher.group(1);
    }
    private MockHttpSession login(String username) throws Exception {
        var page=mvc.perform(get("/login")).andExpect(status().isOk()).andReturn();
        var result=mvc.perform(post("/login").cookie(tokenCookie(page)).param("_csrf",token(page)).param("username",username).param("password",PASSWORD))
            .andExpect(redirectedUrl("/post-login")).andReturn();
        return (MockHttpSession)result.getRequest().getSession(false);
    }
    private MockHttpServletRequestBuilder write(String method,String path,MockHttpSession session,String body) throws Exception {
        var page=mvc.perform(get("/login").session(session)).andExpect(status().isOk()).andReturn();
        return request(org.springframework.http.HttpMethod.valueOf(method),path).session(session)
            .cookie(tokenCookie(page)).param("_csrf",token(page)).contentType("application/json").content(body);
    }
    private void load(MockHttpSession session,String theme) throws Exception {
        mvc.perform(get("/profile/ui-preferences").session(session)).andExpect(status().isOk()).andExpect(jsonPath("$.preferences.theme").value(theme));
    }

    @ParameterizedTest @ValueSource(strings={"reader","ReAdEr"," reader ","имя","anonymousUser"})
    void aBoundAccountReadsItsNumericKeyInsteadOfItsName(String name) throws Exception {
        account(7,name);seed(TYPE,"7","{\"theme\":\"dark\"}");load(login(name),"dark");
    }
    @Test void collisionAfterLoginCannotShareReadsOrWrites() throws Exception {
        account(7,"reader");var session=login("reader");account(99,"ReAdEr");
        seed(TYPE,"7","{\"theme\":\"dark\"}");seed(TYPE,"99","{\"theme\":\"light\"}");
        seed("ui_preferences.v1","ReAdEr","{\"theme\":\"light\"}");
        load(session,"dark");
        mvc.perform(write("PUT","/profile/ui-preferences",session,"{\"theme\":\"light\"}")).andExpect(status().isOk());
        assertThat(jdbc.queryForObject("SELECT extra_json FROM settings_parameters WHERE param_type=? AND value='99'",String.class,TYPE)).isEqualTo("{\"theme\":\"light\"}");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters WHERE param_type=?",Integer.class,TYPE)).isEqualTo(2);
        assertThat(jdbc.queryForObject("SELECT extra_json FROM settings_parameters WHERE param_type='ui_preferences.v1'",String.class)).isEqualTo("{\"theme\":\"light\"}");
    }
    @ParameterizedTest @ValueSource(longs={9007199254740993L,Long.MAX_VALUE})
    void accountKeyDoesNotLoseLongPrecision(long id) throws Exception {
        account(id,"reader");var session=login("reader");
        mvc.perform(write("PUT","/profile/ui-preferences",session,"{\"theme\":\"dark\"}")).andExpect(status().isOk());
        assertThat(jdbc.queryForList("SELECT value FROM settings_parameters WHERE param_type=?",String.class,TYPE)).containsExactly(Long.toString(id));
    }
    @Test void aRenameDoesNotChangePreferenceOwnership() throws Exception {
        account(7,"reader");seed(TYPE,"7","{\"theme\":\"dark\"}");
        jdbc.update("UPDATE users SET username='changed' WHERE id=7");load(login("changed"),"dark");
    }
    @Test void aNewAccountWithAReusedNameDoesNotInheritPreferences() throws Exception {
        account(99,"reader");seed(TYPE,"7","{\"theme\":\"dark\"}");seed("ui_preferences.v1","reader","{\"theme\":\"dark\"}");
        mvc.perform(get("/profile/ui-preferences").session(login("reader"))).andExpect(status().isOk()).andExpect(jsonPath("$.preferences").isEmpty());
    }
    @Test void legacyTriageIsNotImportedByARead() throws Exception {
        account(7,"reader");when(shared.loadSettings()).thenReturn(Map.of("dialog_config",Map.of("workspace_triage_preferences_by_operator",Map.of("reader",Map.of("view","overdue")))));
        mvc.perform(get("/api/dialogs/triage-preferences").session(login("reader"))).andExpect(status().isOk()).andExpect(jsonPath("$.preferences").isEmpty());
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters",Integer.class)).isZero();
    }
    @Test void triageAndBasePreferencesShareOnlyTheirOwnNumericAccountPayload() throws Exception {
        account(7,"reader");seed(TYPE,"7","{\"theme\":\"dark\",\"custom\":\"keep\"}");var session=login("reader");
        mvc.perform(write("POST","/api/dialogs/triage-preferences",session,"{\"view\":\"overdue\",\"sort_mode\":\"sla_priority\",\"page_size\":\"50\"}"))
            .andExpect(status().isOk()).andExpect(jsonPath("$.preferences.view").value("overdue"));
        mvc.perform(write("PUT","/profile/ui-preferences",session,"{\"sidebarPinned\":false}")).andExpect(status().isOk());
        load(session,"dark");
        mvc.perform(get("/api/dialogs/triage-preferences").session(session)).andExpect(status().isOk()).andExpect(jsonPath("$.preferences.page_size").value("50"));
        assertThat(jdbc.queryForObject("SELECT extra_json FROM settings_parameters WHERE param_type=?",String.class,TYPE)).contains("\"custom\":\"keep\"");
    }
    @ParameterizedTest @ValueSource(strings={"duplicate","corrupt"})
    void ambiguousOrCorruptOwnedRowsAreNotSilentlyOverwritten(String mode) throws Exception {
        account(7,"reader");seed(TYPE,"7",mode.equals("corrupt")?"not-json":"{\"theme\":\"dark\"}");
        if(mode.equals("duplicate"))seed(TYPE,"7","{\"theme\":\"light\"}");
        var session=login("reader");
        mvc.perform(write("PUT","/profile/ui-preferences",session,"{\"theme\":\"light\"}")).andExpect(status().isConflict());
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters WHERE param_type=?",Integer.class,TYPE)).isEqualTo(mode.equals("corrupt")?1:2);
    }
    @ParameterizedTest @ValueSource(strings={"legacy","zero","negative","blank","disabled","unauthenticated","anonymous"})
    void directProfileCannotPersistAnUnboundOrInvalidIdentity(String mode) {
        account(7,"reader");
        Object principal=mode.equals("legacy")?User.withUsername("reader").password("fixture").roles("USER").build():
            new PanelUserPrincipal(mode.equals("zero")?0:mode.equals("negative")?-1:7,mode.equals("blank")?" ":"reader","",!mode.equals("disabled"),AuthorityUtils.NO_AUTHORITIES);
        Authentication actor=mode.equals("unauthenticated")?UsernamePasswordAuthenticationToken.unauthenticated(principal,null):
            mode.equals("anonymous")?new AnonymousAuthenticationToken("fixture",principal,AuthorityUtils.createAuthorityList("ROLE_ANONYMOUS")):
            UsernamePasswordAuthenticationToken.authenticated(principal,null,List.of());
        assertThatThrownBy(() -> profile.updateUiPreferences(actor,Map.of("theme","dark"))).isInstanceOf(AccessDeniedException.class);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters",Integer.class)).isZero();
    }
    @Test void htmlBootstrapUsesTheSameAccountAsTheProfileApi() throws Exception {
        account(7,"reader");seed(TYPE,"7","{\"theme\":\"dark\"}");
        mvc.perform(get("/fixture-preferences").session(login("reader"))).andExpect(status().isOk())
            .andExpect(model().attribute("uiPreferencesBootstrap",Map.of("theme","dark"))).andExpect(model().attribute("uiPreferencesSyncEnabled",true));
    }
    @Test void unboundBootstrapDoesNotEnableSynchronization() {
        var actor=UsernamePasswordAuthenticationToken.authenticated("reader",null,List.of());var model=new ExtendedModelMap();
        modelAttributes.addUiPreferenceBootstrap(model,actor);assertThat(model.get("uiPreferencesSyncEnabled")).isEqualTo(false);
    }
    @ParameterizedTest @ValueSource(strings={"POST","PATCH","DELETE"})
    void genericParameterWritesCannotCreateEditOrDeletePrivatePreferences(String method) throws Exception {
        account(7,"reader");long id=seed(TYPE,"7","{\"theme\":\"dark\"}");var session=login("reader");
        String path=method.equals("POST")?"/api/settings/parameters":"/api/settings/parameters/"+id;
        mvc.perform(write(method,path,session,"{\"param_type\":\""+TYPE+"\",\"value\":\"7\",\"theme\":\"light\"}")).andExpect(status().isForbidden());
        assertThat(jdbc.queryForObject("SELECT extra_json FROM settings_parameters WHERE id=?",String.class,id)).isEqualTo("{\"theme\":\"dark\"}");
        assertThat(jdbc.queryForObject("SELECT is_deleted FROM settings_parameters WHERE id=?",Boolean.class,id)).isFalse();
    }
    @Test void genericParameterListHidesPrivateNamespacesEvenIfPresentInCatalog() throws Exception {
        account(7,"reader");seed(TYPE,"7","{\"theme\":\"dark\"}");seed("ui_preferences.v1","reader","{\"theme\":\"light\"}");
        mvc.perform(get("/api/settings/parameters").session(login("reader"))).andExpect(status().isOk())
            .andExpect(jsonPath("$.data['"+TYPE+"']").doesNotExist());
    }
    @ParameterizedTest @ValueSource(strings={"disabled","blocked","deleted","renamed"})
    void revokedSessionsCannotReadOrWritePreferences(String mode) throws Exception {
        account(7,"reader");var session=login("reader");
        switch(mode){case "disabled" -> jdbc.update("UPDATE users SET enabled=FALSE WHERE id=7");case "blocked" -> jdbc.update("UPDATE users SET is_blocked=TRUE WHERE id=7");case "deleted" -> jdbc.update("DELETE FROM users WHERE id=7");default -> jdbc.update("UPDATE users SET username='changed' WHERE id=7");}
        mvc.perform(get("/profile/ui-preferences").session(session)).andExpect(status().is3xxRedirection());
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters",Integer.class)).isZero();
    }
    @Test void missingCsrfCannotWriteAnyPreference() throws Exception {
        account(7,"reader");mvc.perform(put("/profile/ui-preferences").session(login("reader")).contentType("application/json").content("{\"theme\":\"dark\"}"))
            .andExpect(redirectedUrl("/error/403"));
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters",Integer.class)).isZero();
    }
}
