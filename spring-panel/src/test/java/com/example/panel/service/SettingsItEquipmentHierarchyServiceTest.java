package com.example.panel.service;

import com.example.panel.support.PostgresqlJdbcTestSupport;
import static org.assertj.core.api.Assertions.assertThat;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

class SettingsItEquipmentHierarchyServiceTest {

    @Test
    void renamingLocalVendorUpdatesCatalogAndKeepsNetBoxAlias() {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplate("equipment_hierarchy");
        createSchema(jdbc);
        jdbc.update("INSERT INTO it_equipment_catalog(equipment_type, equipment_vendor, equipment_model) VALUES ('Роутер', 'MikroTik', 'RB5009')");

        SettingsItEquipmentHierarchyService service = new SettingsItEquipmentHierarchyService(jdbc);
        service.createBranch(Map.of("node_kind", "vendor", "equipment_type", "Роутер", "equipment_vendor", "MikroTik"));
        Long branchId = jdbc.queryForObject("SELECT id FROM it_equipment_hierarchy_branches", Long.class);

        Map<String, Object> result = service.renameBranch(branchId, Map.of("name", "MikroTik Local"));

        assertThat(result.get("success")).isEqualTo(true);
        assertThat(jdbc.queryForObject("SELECT equipment_vendor FROM it_equipment_catalog", String.class)).isEqualTo("MikroTik Local");
        assertThat(jdbc.queryForMap("SELECT source_vendor, target_vendor FROM it_equipment_catalog_aliases"))
                .containsEntry("source_vendor", "MikroTik")
                .containsEntry("target_vendor", "MikroTik Local");
    }

    @Test
    void renamingLocalTypeMovesConfigurationWithCatalog() {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplate("equipment_type_hierarchy");
        createSchema(jdbc);
        jdbc.update("INSERT INTO it_equipment_catalog(equipment_type, equipment_vendor, equipment_model) VALUES ('Роутер', 'MikroTik', 'RB5009')");
        jdbc.update("INSERT INTO it_equipment_attribute_definitions(equipment_type, attribute_key) VALUES ('Роутер', 'ports')");
        jdbc.update("INSERT INTO it_equipment_configuration_profiles(equipment_type, profile_name) VALUES ('Роутер', 'Базовый')");

        SettingsItEquipmentHierarchyService service = new SettingsItEquipmentHierarchyService(jdbc);
        service.createBranch(Map.of("node_kind", "type", "equipment_type", "Роутер"));
        Long branchId = jdbc.queryForObject("SELECT id FROM it_equipment_hierarchy_branches WHERE node_kind = 'type'", Long.class);

        Map<String, Object> result = service.renameBranch(branchId, Map.of("name", "Маршрутизатор"));

        assertThat(result.get("success")).isEqualTo(true);
        assertThat(jdbc.queryForObject("SELECT equipment_type FROM it_equipment_catalog", String.class)).isEqualTo("Маршрутизатор");
        assertThat(jdbc.queryForObject("SELECT equipment_type FROM it_equipment_attribute_definitions", String.class)).isEqualTo("Маршрутизатор");
        assertThat(jdbc.queryForObject("SELECT equipment_type FROM it_equipment_configuration_profiles", String.class)).isEqualTo("Маршрутизатор");
    }

    private void createSchema(JdbcTemplate jdbc) {
        jdbc.execute("""
                CREATE TABLE it_equipment_catalog (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    equipment_type TEXT NOT NULL, equipment_vendor TEXT NOT NULL, equipment_model TEXT NOT NULL,
                    photo_url TEXT, serial_number TEXT, accessories TEXT, created_at TIMESTAMPTZ, updated_at TIMESTAMPTZ
                )
                """);
        jdbc.execute("""
                CREATE TABLE it_equipment_hierarchy_branches (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    node_kind VARCHAR(16) NOT NULL, equipment_type TEXT NOT NULL, equipment_vendor TEXT NOT NULL DEFAULT '',
                    created_at TIMESTAMPTZ, updated_at TIMESTAMPTZ
                )
                """);
        jdbc.execute("""
                CREATE TABLE it_equipment_catalog_aliases (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    source_type TEXT NOT NULL, source_vendor TEXT NOT NULL DEFAULT '', source_model TEXT NOT NULL,
                    target_type TEXT NOT NULL, target_vendor TEXT NOT NULL DEFAULT '', target_model TEXT NOT NULL,
                    created_at TIMESTAMPTZ, updated_at TIMESTAMPTZ,
                    UNIQUE(source_type, source_vendor, source_model)
                )
                """);
        jdbc.execute("""
                CREATE TABLE it_equipment_attribute_definitions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    equipment_type TEXT NOT NULL, attribute_key TEXT NOT NULL, updated_at TIMESTAMPTZ
                )
                """);
        jdbc.execute("""
                CREATE TABLE it_equipment_configuration_profiles (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    equipment_type TEXT NOT NULL, profile_name TEXT NOT NULL, updated_at TIMESTAMPTZ
                )
                """);
    }
}
