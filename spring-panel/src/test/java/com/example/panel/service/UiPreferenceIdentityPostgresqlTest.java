package com.example.panel.service;

import com.example.panel.security.PanelUserPrincipal;
import com.example.panel.support.PostgresqlJdbcTestSupport;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.util.List;
import java.util.Map;
import java.util.concurrent.*;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.dao.DataAccessResourceFailureException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.Authentication;
import org.springframework.web.server.ResponseStatusException;

import static org.assertj.core.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

class UiPreferenceIdentityPostgresqlTest {
    private static final String TYPE="ui_preferences.account.v2";
    private JdbcTemplate jdbc;
    private UiPreferenceService service;
    @BeforeEach void setup() {
        jdbc=PostgresqlJdbcTestSupport.freshJdbcTemplate("preference_owner_sql");
        jdbc.execute("CREATE TABLE users(id BIGINT PRIMARY KEY,username TEXT UNIQUE,enabled BOOLEAN DEFAULT TRUE,is_blocked BOOLEAN DEFAULT FALSE)");
        jdbc.execute("CREATE TABLE settings_parameters(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,param_type TEXT,value TEXT,state TEXT,is_deleted BOOLEAN DEFAULT FALSE,deleted_at TIMESTAMP,extra_json TEXT)");
        jdbc.update("INSERT INTO users(id,username) VALUES(7,'reader')");
        service=new UiPreferenceService(jdbc,new ObjectMapper());
    }
    private Authentication actor(long id,String name) {
        return UsernamePasswordAuthenticationToken.authenticated(new PanelUserPrincipal(id,name,"",true,List.of()),null,List.of());
    }
    private void unavailable(Runnable operation) {
        assertThatThrownBy(operation::run).isInstanceOfSatisfying(ResponseStatusException.class,
            ex -> assertThat(ex.getStatusCode().value()).isEqualTo(503));
    }
    @Test void concurrentFirstBaseAndTriageSavesNeverDuplicateOrLoseEachOther() throws Exception {
        var executor=Executors.newFixedThreadPool(2);var actor=actor(7,"reader");
        try {
            for(int round=0;round<5;round++){
                jdbc.update("DELETE FROM settings_parameters");
                var start=new CountDownLatch(1);
                var base=executor.submit(() -> {start.await();return service.saveForUser(actor,Map.of("theme","dark"));});
                var triage=executor.submit(() -> {start.await();return service.saveDialogsTriageForUser(actor,Map.of("view","overdue","page_size","50"));});
                start.countDown();base.get(20,TimeUnit.SECONDS);triage.get(20,TimeUnit.SECONDS);
                assertThat(service.loadForUser(actor)).containsEntry("theme","dark");
                assertThat(service.loadDialogsTriageForUser(actor)).containsEntry("view","overdue").containsEntry("page_size","50");
                assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters",Integer.class)).isEqualTo(1);
            }
        } finally {executor.shutdownNow();}
    }
    @ParameterizedTest @ValueSource(strings={"disabled","blocked","renamed","deleted","unknown-id","wrong-name"})
    void changedOrMismatchingAccountCannotLoadOrPersist(String state) {
        switch(state){case "disabled" -> jdbc.update("UPDATE users SET enabled=FALSE");case "blocked" -> jdbc.update("UPDATE users SET is_blocked=TRUE");
            case "renamed" -> jdbc.update("UPDATE users SET username='changed'");case "deleted" -> jdbc.update("DELETE FROM users");default -> {}}
        var actor=actor(state.equals("unknown-id")?99:7,state.equals("wrong-name")?"READER":"reader");
        assertThatThrownBy(() -> service.loadForUser(actor)).isInstanceOf(AccessDeniedException.class);
        assertThatThrownBy(() -> service.saveForUser(actor,Map.of("theme","dark"))).isInstanceOf(AccessDeniedException.class);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters",Integer.class)).isZero();
    }
    @Test void aStorageReadFailureCannotReturnSuccessOrReplaceData() {
        jdbc.update("INSERT INTO settings_parameters(param_type,value,extra_json) VALUES(?,'7',?)",TYPE,"{\"theme\":\"dark\"}");
        var failing=spy(jdbc);
        doThrow(new DataAccessResourceFailureException("fixture unavailable")).when(failing)
            .queryForList(startsWith("SELECT id, extra_json"),any(Object[].class));
        var broken=new UiPreferenceService(failing,new ObjectMapper());
        unavailable(() -> broken.saveForUser(actor(7,"reader"),Map.of("theme","light")));
        assertThat(jdbc.queryForObject("SELECT extra_json FROM settings_parameters",String.class)).isEqualTo("{\"theme\":\"dark\"}");
    }
    @Test void aFailureAfterTheSqlInsertRollsBackTheWholePreferenceWrite() {
        var failing=spy(jdbc);
        doAnswer(call -> {call.callRealMethod();throw new DataAccessResourceFailureException("fixture after insert");})
            .when(failing).update(startsWith("INSERT INTO settings_parameters"),any(Object[].class));
        var broken=new UiPreferenceService(failing,new ObjectMapper());
        unavailable(() -> broken.saveForUser(actor(7,"reader"),Map.of("theme","dark")));
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters",Integer.class)).isZero();
    }
    @Test void softDeletedDataIsNotRevivedOrOverwritten() {
        jdbc.update("INSERT INTO settings_parameters(param_type,value,is_deleted,extra_json) VALUES(?,'7',TRUE,?)",TYPE,"{\"theme\":\"light\"}");
        service.saveForUser(actor(7,"reader"),Map.of("theme","dark"));
        assertThat(service.loadForUser(actor(7,"reader"))).containsEntry("theme","dark");
        assertThat(jdbc.queryForObject("SELECT extra_json FROM settings_parameters WHERE is_deleted=TRUE",String.class)).isEqualTo("{\"theme\":\"light\"}");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters WHERE is_deleted=FALSE",Integer.class)).isEqualTo(1);
    }
    @ParameterizedTest @ValueSource(strings={"007","+7","reader","7 "})
    void nonCanonicalKeysNeverBecomeAccountAliases(String key) {
        jdbc.update("INSERT INTO settings_parameters(param_type,value,extra_json) VALUES(?,?,?)",TYPE,key,"{\"theme\":\"light\"}");
        assertThat(service.loadForUser(actor(7,"reader"))).isEmpty();
        service.saveForUser(actor(7,"reader"),Map.of("theme","dark"));
        assertThat(jdbc.queryForObject("SELECT extra_json FROM settings_parameters WHERE value=?",String.class,key)).isEqualTo("{\"theme\":\"light\"}");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM settings_parameters WHERE value='7'",Integer.class)).isEqualTo(1);
    }
}
