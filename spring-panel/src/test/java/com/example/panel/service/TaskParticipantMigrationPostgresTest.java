package com.example.panel.service;

import com.example.panel.support.PostgresqlJdbcTestSupport;
import java.nio.charset.StandardCharsets;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import static org.assertj.core.api.Assertions.assertThat;

class TaskParticipantMigrationPostgresTest {
    @Test void migrationBindsOnlyExactUnambiguousRosterAccountsAndDeletionCannotRebind() throws Exception {
        var jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplateDefaultStringType("task_participant_upgrade");
        jdbc.execute("CREATE TABLE users(id BIGINT PRIMARY KEY,username TEXT);CREATE TABLE tasks(id BIGINT PRIMARY KEY,assignee TEXT);CREATE TABLE task_people(id BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 100) PRIMARY KEY,task_id BIGINT,identity TEXT,role TEXT)");
        jdbc.execute("INSERT INTO users VALUES(1,'Anna'),(2,'anna'),(3,'duplicate'),(4,'duplicate'),(5,'trim');"+
            "INSERT INTO task_people VALUES(1,10,'Anna','assignee'),(2,10,'anna','co'),(3,10,'duplicate','watcher'),(4,10,' trim ','watcher'),(5,10,'missing','watcher'),(6,10,'Anna','creator')");
        jdbc.execute("INSERT INTO tasks VALUES(10,'Anna'),(11,'anna'),(12,'missing'),(13,' trim '),(14,NULL),(15,'duplicate')");
        jdbc.execute(new ClassPathResource("db/migration/postgresql/V109__task_participant_account_binding.sql").getContentAsString(StandardCharsets.UTF_8));
        assertThat(jdbc.queryForObject("SELECT user_id FROM task_people WHERE id=1",Long.class)).isEqualTo(1L);
        assertThat(jdbc.queryForObject("SELECT user_id FROM task_people WHERE id=2",Long.class)).isEqualTo(2L);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM task_people WHERE id IN(3,4,5,6) AND user_id IS NULL",Integer.class)).isEqualTo(4);
        assertThat(jdbc.queryForObject("SELECT user_id FROM task_people WHERE task_id=11 AND role='assignee'",Long.class)).isEqualTo(2L);
        assertThat(jdbc.queryForObject("SELECT identity FROM task_people WHERE task_id=12",String.class)).isEqualTo("missing");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM task_people WHERE task_id IN(12,13,15) AND user_id IS NULL",Integer.class)).isEqualTo(3);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM task_people WHERE task_id=14",Integer.class)).isZero();
        jdbc.execute("DELETE FROM users WHERE id=1;INSERT INTO users VALUES(99,'Anna')");
        assertThat(jdbc.queryForObject("SELECT user_id FROM task_people WHERE id=1",Long.class)).isNull();
        assertThat(jdbc.queryForObject("SELECT identity FROM task_people WHERE id=1",String.class)).isEqualTo("Anna");
    }
}
