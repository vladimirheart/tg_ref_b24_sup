package com.example.panel.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

import com.example.panel.entity.Channel;
import com.example.panel.support.PostgresqlJdbcTestSupport;
import java.util.Optional;
import java.util.stream.Stream;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.mock.web.MockMultipartFile;

/** Real PostgreSQL history writes after a simulated successful provider delivery. */
class DialogReplyHistoryPostgresqlTest {
    static Stream<Arguments> replies() {
        return Stream.of(true, false).flatMap(identity -> Stream.of("T-REPLY", " T-REPLY ")
                .flatMap(ticket -> Stream.of(false, true).map(media -> Arguments.of(identity, ticket, media))));
    }

    @ParameterizedTest
    @MethodSource("replies")
    void deliveredReplyPersistsOwnerAuthorAndProviderIdBeforeReturningSuccess(
            boolean identityColumn, String ticket, boolean media) {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplateDefaultStringType("reply_history");
        jdbc.execute("CREATE TABLE tickets(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,PRIMARY KEY(user_id,ticket_id))");
        jdbc.execute("CREATE TABLE messages(user_id BIGINT,ticket_id TEXT UNIQUE,channel_id BIGINT,created_at TIMESTAMPTZ)");
        jdbc.execute("""
                CREATE TABLE chat_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT,sender TEXT,message TEXT,timestamp TIMESTAMPTZ,ticket_id TEXT,
                    message_type TEXT,attachment TEXT,channel_id BIGINT,tg_message_id BIGINT,
                    reply_to_tg_id BIGINT,ticket_owner_user_id BIGINT NOT NULL)
                """);
        if (identityColumn) jdbc.execute("ALTER TABLE chat_history ADD COLUMN sender_identity TEXT");
        jdbc.execute("CREATE TABLE ticket_active(ticket_id TEXT PRIMARY KEY,user_identity TEXT,last_seen TIMESTAMPTZ)");
        jdbc.execute("CREATE TABLE web_form_sessions(ticket_id TEXT)");
        jdbc.update("INSERT INTO tickets VALUES (42,?,77)", ticket);
        jdbc.update("INSERT INTO messages VALUES (42,?,77,CURRENT_TIMESTAMP)", ticket);
        // A different exact ID and channel must not supply the owner or receive the history.
        jdbc.update("INSERT INTO tickets VALUES (99,?,88)", ticket.equals(ticket.trim()) ? "other" : ticket.trim());
        var metadata = mock(ChatAttachmentMetadataService.class);
        var targets = new DialogReplyTargetService(jdbc, metadata, new LegacyTicketIdJdbcGuard(jdbc));
        var transport = mock(DialogReplyTransportService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var channel = new Channel();
        channel.setId(77L);
        channel.setPlatform("telegram");
        channel.setToken("test-only-token");
        when(transport.loadChannel(77L)).thenReturn(Optional.of(channel));
        when(responsibility.assignResponsibleIfMissing(ticket, "other_operator")).thenReturn("other_operator");
        var delivered = DialogReplyTransportService.DialogReplyTransportResult.success(901L, 77L);
        var replies = new DialogReplyService(targets, transport, responsibility, ledger);
        var file = new MockMultipartFile("file", "photo.png", "image/png", new byte[] {1, 2, 3});
        if (media) {
            when(transport.sendMedia(channel, 42L, file, "Ответ", "photo.png", 800L)).thenReturn(delivered);
            var result = replies.sendMediaReply(ticket, file, "Ответ", 800L, "other_operator",
                    "stored.png", "photo.png", "image/png", 3L);
            assertThat(result.success()).isTrue();
            assertThat(result.timestamp()).isNotBlank();
            assertThat(result.telegramMessageId()).isEqualTo(901L);
            assertThat(result.responsible()).isEqualTo("other_operator");
            verify(transport).sendMedia(channel, 42L, file, "Ответ", "photo.png", 800L);
        } else {
            when(transport.sendText(channel, 42L, "Ответ", 800L)).thenReturn(delivered);
            var result = replies.sendReply(ticket, "Ответ", 800L, "other_operator");
            assertThat(result.success()).isTrue();
            assertThat(result.timestamp()).isNotBlank();
            assertThat(result.telegramMessageId()).isEqualTo(901L);
            assertThat(result.responsible()).isEqualTo("other_operator");
            verify(transport).sendText(channel, 42L, "Ответ", 800L);
        }
        var rows = jdbc.queryForList("SELECT * FROM chat_history");
        assertThat(rows).hasSize(1);
        var row = rows.get(0);
        assertThat(row).containsEntry("user_id", 42L).containsEntry("ticket_owner_user_id", 42L)
                .containsEntry("channel_id", 77L).containsEntry("ticket_id", ticket)
                .containsEntry("sender", "operator").containsEntry("message", "Ответ")
                .containsEntry("tg_message_id", 901L).containsEntry("reply_to_tg_id", 800L);
        if (identityColumn) assertThat(row).containsEntry("sender_identity", "other_operator");
        assertThat(row.get("timestamp")).isNotNull();
        if (media) {
            assertThat(row).containsEntry("attachment", "stored.png");
            verify(metadata).upsertForChatHistory(((Number) row.get("id")).longValue(), ticket, 77L,
                    "stored.png", "photo.png", "image/png", 3L, (String) row.get("message_type"));
        } else {
            assertThat(row).containsEntry("message_type", "operator_message").containsEntry("attachment", null);
            verifyNoInteractions(metadata);
        }
        verify(ledger).recordAttempt(channel, ticket, 42L, "operator", media ? (String) row.get("message_type") : "text", 800L, delivered);
        verify(responsibility).assignResponsibleIfMissing(ticket, "other_operator");
        assertThat(jdbc.queryForObject("SELECT user_identity FROM ticket_active WHERE ticket_id=?", String.class, ticket))
                .isEqualTo("other_operator");
    }
}
