class DialogOutgoingConditionalInsertPostgresqlTest {
    private record Fixture(JdbcTemplate jdbc, DialogReplyTargetService targets,
                           ChatAttachmentMetadataService metadata, AttachmentObjectStorageService storage) { }

    private Fixture fixture(String owner) {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplate("outgoing_conditional_insert");
        jdbc.execute("CREATE TABLE tickets(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,PRIMARY KEY(user_id,ticket_id))");
        jdbc.execute("CREATE TABLE messages(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("""
                CREATE TABLE chat_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT,sender TEXT,message TEXT,timestamp TIMESTAMPTZ,ticket_id TEXT,message_type TEXT,
                    attachment TEXT,channel_id BIGINT,tg_message_id BIGINT,reply_to_tg_id BIGINT,
                    ticket_owner_user_id BIGINT)
                """);
        jdbc.execute("""
                CREATE TABLE chat_attachment_metadata(
                    chat_history_id BIGINT UNIQUE REFERENCES chat_history(id),ticket_id TEXT,channel_id BIGINT,
                    storage_key TEXT,storage_provider TEXT,storage_class TEXT,original_name TEXT,mime_type TEXT,size BIGINT,
                    content_hash TEXT,legacy_attachment_ref TEXT,normalization_status TEXT,availability_status TEXT,
                    created_at TIMESTAMPTZ,updated_at TIMESTAMPTZ,archived_at TIMESTAMPTZ,deleted_at TIMESTAMPTZ)
                """);
        jdbc.execute("CREATE TABLE ticket_active(ticket_id TEXT PRIMARY KEY,user_identity TEXT,last_seen TIMESTAMPTZ)");
        jdbc.execute("CREATE TABLE web_form_sessions(ticket_id TEXT)");
        jdbc.update("INSERT INTO tickets VALUES (42,?,77)", owner);
        jdbc.update("INSERT INTO messages(user_id,ticket_id,channel_id) VALUES (42,?,77)", owner);
        if (!owner.equals(owner.trim())) {
            jdbc.update("INSERT INTO tickets VALUES (88,?,88)", owner.trim());
            jdbc.update("INSERT INTO messages(user_id,ticket_id,channel_id) VALUES (88,?,88)", owner.trim());
        }
        var storage = mock(AttachmentObjectStorageService.class);
        when(storage.providerLabel()).thenReturn("local_fs");
        var metadata = spy(new ChatAttachmentMetadataService(jdbc, storage));
        var targets = spy(new DialogReplyTargetService(jdbc, metadata, new LegacyTicketIdJdbcGuard(jdbc)));
        return new Fixture(jdbc, targets, metadata, storage);
    }

    private void changeOwner(Fixture fixture, String condition) {
        switch (condition) {
            case "duplicate" -> fixture.jdbc().execute("INSERT INTO tickets VALUES (99,'T',77)");
            case "missing" -> fixture.jdbc().execute("DELETE FROM tickets");
            case "user" -> fixture.jdbc().execute("UPDATE tickets SET user_id=99");
            case "channel" -> fixture.jdbc().execute("UPDATE tickets SET channel_id=88");
            case "both" -> fixture.jdbc().execute("UPDATE tickets SET user_id=99,channel_id=88");
            default -> throw new IllegalArgumentException(condition);
        }
    }

    private AtomicInteger changeAfterProof(Fixture fixture, String condition, int proofNumber) {
        var proofs = new AtomicInteger();
        doAnswer(call -> {
            boolean allowed = (boolean) call.callRealMethod();
            if (allowed && proofs.incrementAndGet() == proofNumber) {
                // A committed owner change after proof, before the INSERT statement snapshot.
                changeOwner(fixture, condition);
            }
            return allowed;
        }).when(fixture.targets()).hasReplyTargetOwner(eq("T"), any(DialogReplyTarget.class));
        return proofs;
    }

    private void assertNoHistoryMetadataOrActivity(Fixture fixture) {
        for (String table : new String[] {"chat_history", "chat_attachment_metadata", "ticket_active"}) {
            assertThat(fixture.jdbc().queryForObject("SELECT COUNT(*) FROM " + table, Integer.class))
                    .as(table).isZero();
        }
        verifyNoInteractions(fixture.metadata(), fixture.storage());
    }

    private String write(Fixture fixture, String owner, String kind, Long providerId, Long replyId) {
        var target = new DialogReplyTarget(42L, 77L);
        return "text".equals(kind)
                ? fixture.targets().logOutgoingMessage(target, owner, " raw reply ", "operator_message",
                        providerId, replyId, " AI_AGENT ")
                : fixture.targets().logOutgoingMediaMessage(target, owner, "caption", "stored.png",
                        "photo.png", "image/png", 3L, "image", providerId, replyId);
    }

    static Stream<Arguments> rejectedDirectInserts() {
        return Stream.of("duplicate", "missing", "user", "channel", "both")
                .flatMap(condition -> Stream.of("text", "media").map(kind -> Arguments.of(condition, kind)));
    }

    @ParameterizedTest
    @MethodSource("rejectedDirectInserts")
    void lateParentChangeCannotInsertHistoryOrMediaMetadata(String condition, String kind) {
        Fixture fixture = fixture("T");
        AtomicInteger proofs = changeAfterProof(fixture, condition, 1);

        assertThatThrownBy(() -> write(fixture, "T", kind, 900L, 800L))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessage("Outgoing message requires a unique legacy ticket id.");

        assertThat(proofs).hasValue(1);
        assertNoHistoryMetadataOrActivity(fixture);
    }

    static Stream<Arguments> validInserts() {
        return Stream.of("T", " T ", "T/100", " T/100?&%#+ Ю ", "T%2F+", " null ")
                .flatMap(owner -> Stream.of("text", "media")
                        .flatMap(kind -> Stream.of(false, true).map(nullable -> Arguments.of(owner, kind, nullable))));
    }

    @ParameterizedTest
    @MethodSource("validInserts")
    void validExactInsertKeepsBindingsNullIdsTimestampAndGeneratedMetadata(String owner, String kind, boolean nullable) {
        Fixture fixture = fixture(owner);
        Long providerId = nullable ? null : 900L;
        Long replyId = nullable ? null : 800L;

        String timestamp = write(fixture, owner, kind, providerId, replyId);

        assertThat(OffsetDateTime.parse(timestamp)).isNotNull();
        var row = fixture.jdbc().queryForMap("SELECT * FROM chat_history");
        assertThat(row.get("id")).isInstanceOf(Long.class);
        assertThat((Long) row.get("id")).isPositive();
        assertThat(row.get("user_id")).isEqualTo(42L);
        assertThat(row.get("ticket_id")).isEqualTo(owner);
        assertThat(row.get("ticket_owner_user_id")).isEqualTo(42L);
        assertThat(row.get("channel_id")).isEqualTo(77L);
        assertThat(row.get("timestamp")).isNotNull();
        assertThat(row.get("tg_message_id")).isEqualTo(providerId);
        assertThat(row.get("reply_to_tg_id")).isEqualTo(replyId);
        if ("text".equals(kind)) {
            assertThat(row.get("sender")).isEqualTo("ai_agent");
            assertThat(row.get("message")).isEqualTo(" raw reply ");
            assertThat(row.get("message_type")).isEqualTo("operator_message");
            assertThat(row.get("attachment")).isNull();
            assertThat(fixture.jdbc().queryForObject("SELECT COUNT(*) FROM chat_attachment_metadata", Integer.class)).isZero();
            verifyNoInteractions(fixture.metadata(), fixture.storage());
        } else {
            assertThat(row.get("sender")).isEqualTo("operator");
            assertThat(row.get("message")).isEqualTo("caption");
            assertThat(row.get("message_type")).isEqualTo("image");
            assertThat(row.get("attachment")).isEqualTo("stored.png");
            var metadata = fixture.jdbc().queryForMap("SELECT * FROM chat_attachment_metadata");
            assertThat(metadata.get("chat_history_id")).isEqualTo(row.get("id"));
            assertThat(metadata.get("ticket_id")).isEqualTo(owner);
            assertThat(metadata.get("channel_id")).isEqualTo(77L);
            assertThat(metadata.get("original_name")).isEqualTo("photo.png");
            assertThat(metadata.get("mime_type")).isEqualTo("image/png");
            assertThat(metadata.get("size")).isEqualTo(3L);
            verify(fixture.metadata()).upsertForChatHistory((Long) row.get("id"), owner, 77L,
                    "stored.png", "photo.png", "image/png", 3L, "image");
        }
    }

    static Stream<Arguments> rejectedReplyFlows() {
        return Stream.of("duplicate", "missing", "both")
                .flatMap(condition -> Stream.of("text", "media", "web").map(kind -> Arguments.of(condition, kind)));
    }

    @ParameterizedTest
    @MethodSource("rejectedReplyFlows")
    void failedConditionalWriteDoesNotProceedToActivityOrResponsibility(String condition, String kind) {
        Fixture fixture = fixture("T");
        AtomicInteger proofs = changeAfterProof(fixture, condition, 2);
        if ("web".equals(kind)) fixture.jdbc().execute("INSERT INTO web_form_sessions VALUES ('T')");
        var transport = mock(DialogReplyTransportService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        Channel channel = new Channel();
        channel.setId(77L); channel.setPlatform("telegram"); channel.setToken("controlled-token");
        when(transport.loadChannel(77L)).thenReturn(Optional.of(channel));
        when(transport.sendText(channel, 42L, "reply", 800L))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        var file = new MockMultipartFile("file", "photo.png", "image/png", new byte[] {1, 2, 3});
        when(transport.sendMedia(channel, 42L, file, "caption", "photo.png", 800L))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        var replies = new DialogReplyService(fixture.targets(), transport, responsibility, ledger);

        assertThatThrownBy(() -> {
            if ("media".equals(kind)) {
                replies.sendMediaReply("T", file, "caption", 800L, "operator",
                        "stored.png", "photo.png", "image/png", 3L);
            } else {
                replies.sendReply("T", "reply", 800L, "operator");
            }
        }).isInstanceOf(IllegalArgumentException.class)
                .hasMessage("Outgoing message requires a unique legacy ticket id.");

        assertThat(proofs).hasValue(2);
        assertNoHistoryMetadataOrActivity(fixture);
        verifyNoInteractions(responsibility);
        if ("web".equals(kind)) {
            verifyNoInteractions(ledger);
        } else {
            verify(ledger).recordAttempt(eq(channel), eq("T"), eq(42L), eq("operator"),
                    eq("media".equals(kind) ? "image" : "text"), eq(800L), any());
        }
    }
}
