package com.example.panel.service.integration;

import static org.assertj.core.api.Assertions.assertThat;

import com.example.panel.support.PostgresqlJdbcTestSupport;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.zaxxer.hikari.HikariDataSource;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicBoolean;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.TestInstance;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.support.TransactionTemplate;

/** Two real transactions read the same retry candidate before either can update it. */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class InboundInboxClaimPostgresTest {
    private HikariDataSource pool;
    private JdbcTemplate jdbc;
    private String schema;

    @BeforeAll
    void setup() {
        JdbcTemplate owned = PostgresqlJdbcTestSupport.freshJdbcTemplate("r317_inbox_claim");
        schema = owned.queryForObject("SELECT current_schema()", String.class);
        DriverManagerDataSource source = (DriverManagerDataSource) owned.getDataSource();
        pool = new HikariDataSource();
        pool.setJdbcUrl(source.getUrl());
        pool.setUsername(source.getUsername());
        pool.setPassword(source.getPassword());
        pool.setMaximumPoolSize(6);
        pool.setMinimumIdle(0);
        pool.setConnectionTimeout(15000);
        jdbc = new JdbcTemplate(pool);
        jdbc.execute("""
            CREATE TABLE integration_inbound_event_inbox (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                event_id TEXT NOT NULL UNIQUE, event_kind TEXT NOT NULL,
                platform TEXT NOT NULL, channel_id BIGINT NOT NULL, ticket_id TEXT NOT NULL,
                transport_source TEXT NOT NULL, routing_key TEXT, payload_json TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'received',
                received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                processed_at TIMESTAMPTZ, last_error TEXT,
                attempt_count INTEGER DEFAULT 0, processing_started_at TIMESTAMPTZ,
                updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """);
    }

    @AfterAll
    void cleanup() {
        try {
            if (jdbc != null && schema != null && schema.matches("r317_inbox_claim_[a-f0-9]{12}"))
                jdbc.execute("DROP SCHEMA " + schema + " CASCADE");
        } finally {
            if (pool != null) pool.close();
        }
    }

    @ParameterizedTest
    @CsvSource({"telegram,failed", "vk,failed", "max,failed",
        "telegram,received", "vk,received", "max,received",
        "telegram,stale", "vk,stale", "max,stale"})
    void concurrentRecoveryHasExactlyOneWinner(String platform, String state) throws Exception {
        String eventId = seed(platform, state);
        CountDownLatch readers = new CountDownLatch(2);
        var service = new IntegrationInboundEventInboxService(new JdbcTemplate(pool) {
            @Override public int update(String sql, Object... args) {
                if (sql.contains("attempt_count = COALESCE")) {
                    readers.countDown();
                    await(readers);
                }
                return super.update(sql, args);
            }
        }, new ObjectMapper());
        var executor = Executors.newFixedThreadPool(2);
        try {
            var first = executor.submit(() -> claim(service, platform, eventId, "worker-a"));
            var second = executor.submit(() -> claim(service, platform, eventId, "worker-b"));
            boolean a = first.get(15, TimeUnit.SECONDS), b = second.get(15, TimeUnit.SECONDS);
            assertThat(List.of(a, b)).containsExactlyInAnyOrder(true, false);
            assertThat(jdbc.queryForObject("SELECT attempt_count FROM integration_inbound_event_inbox WHERE event_id=?",
                Integer.class, eventId)).isEqualTo(2);
            assertThat(jdbc.queryForObject("SELECT routing_key FROM integration_inbound_event_inbox WHERE event_id=?",
                String.class, eventId)).isEqualTo(a ? "worker-a" : "worker-b");
            assertThat(claim(service(), platform, eventId, "third-worker")).isFalse();
        } finally {
            executor.shutdownNow();
            assertThat(executor.awaitTermination(15, TimeUnit.SECONDS)).isTrue();
        }
    }

    @ParameterizedTest @ValueSource(strings={"telegram", "vk", "max"})
    void staleReaderCannotStealANewerFailedAttempt(String platform) throws Exception {
        String eventId = seed(platform, "failed");
        CountDownLatch staleRead = new CountDownLatch(1), release = new CountDownLatch(1);
        AtomicBoolean pause = new AtomicBoolean(true);
        var stale = new IntegrationInboundEventInboxService(new JdbcTemplate(pool) {
            @Override public int update(String sql, Object... args) {
                if (sql.contains("attempt_count = COALESCE") && pause.compareAndSet(true, false)) {
                    staleRead.countDown();
                    await(release);
                }
                return super.update(sql, args);
            }
        }, new ObjectMapper());
        var executor = Executors.newSingleThreadExecutor();
        try {
            var oldReader = executor.submit(() -> claim(stale, platform, eventId, "stale-reader"));
            await(staleRead);
            assertThat(claim(service(), platform, eventId, "new-attempt")).isTrue();
            service().markFailed(eventId, new IllegalStateException("fixture failure"));
            release.countDown();
            assertThat(oldReader.get(15, TimeUnit.SECONDS)).isFalse();
            assertThat(jdbc.queryForObject("SELECT attempt_count FROM integration_inbound_event_inbox WHERE event_id=?",
                Integer.class, eventId)).isEqualTo(2);
            assertThat(jdbc.queryForObject("SELECT routing_key FROM integration_inbound_event_inbox WHERE event_id=?",
                String.class, eventId)).isEqualTo("new-attempt");
            // A fresh reader can still recover that failure, then a committed success stays final.
            assertThat(claim(service(), platform, eventId, "fresh-reader")).isTrue();
            new TransactionTemplate(new DataSourceTransactionManager(pool))
                .executeWithoutResult(status -> service().markProcessed(eventId));
            assertThat(claim(service(), platform, eventId, "processed-replay")).isFalse();
        } finally {
            release.countDown();
            executor.shutdownNow();
            assertThat(executor.awaitTermination(15, TimeUnit.SECONDS)).isTrue();
        }
    }

    @ParameterizedTest @ValueSource(strings={"telegram", "vk", "max"})
    void simultaneousFirstDeliveryHasOneWinner(String platform) throws Exception {
        String eventId = UUID.randomUUID().toString();
        var executor = Executors.newFixedThreadPool(2);
        CountDownLatch ready = new CountDownLatch(2);
        try {
            var first = executor.submit(() -> {ready.countDown(); await(ready); return claim(service(), platform, eventId, "a");});
            var second = executor.submit(() -> {ready.countDown(); await(ready); return claim(service(), platform, eventId, "b");});
            assertThat(List.of(first.get(15, TimeUnit.SECONDS), second.get(15, TimeUnit.SECONDS)))
                .containsExactlyInAnyOrder(true, false);
            assertThat(jdbc.queryForObject("SELECT attempt_count FROM integration_inbound_event_inbox WHERE event_id=?",
                Integer.class, eventId)).isEqualTo(1);
        } finally {
            executor.shutdownNow();
            assertThat(executor.awaitTermination(15, TimeUnit.SECONDS)).isTrue();
        }
    }

    private IntegrationInboundEventInboxService service() {
        return new IntegrationInboundEventInboxService(jdbc, new ObjectMapper());
    }

    private boolean claim(IntegrationInboundEventInboxService service, String platform, String eventId, String route) {
        return Boolean.TRUE.equals(new TransactionTemplate(new DataSourceTransactionManager(pool)).execute(status ->
            service.beginProcessing(eventId, "client_message.active_ticket", platform, 25L, " raw/Ю% ",
                route, Map.of("text", "same captured message"), null)));
    }

    private String seed(String platform, String state) {
        String eventId = UUID.randomUUID().toString();
        assertThat(claim(service(), platform, eventId, "original")).isTrue();
        jdbc.update("""
            UPDATE integration_inbound_event_inbox SET status=?,
                processing_started_at=CURRENT_TIMESTAMP - INTERVAL '30 minutes'
            WHERE event_id=?
            """, state.equals("stale") ? "processing" : state, eventId);
        return eventId;
    }

    private static void await(CountDownLatch latch) {
        try {
            if (!latch.await(10, TimeUnit.SECONDS)) throw new AssertionError("Concurrent inbox fixture timed out");
        } catch (InterruptedException ex) {
            Thread.currentThread().interrupt();
            throw new AssertionError(ex);
        }
    }
}
