class DialogOutgoingTargetOwnershipPostgresqlTest {
    private record Fixture(JdbcTemplate jdbc, DialogReplyTargetService targets,
                           ChatAttachmentMetadataService metadata, AttachmentObjectStorageService storage) { }

    private Fixture fixture(String owner, boolean failedTargetLookup) {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplate("outgoing_target_owner");
        jdbc.execute("CREATE TABLE tickets(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,PRIMARY KEY(user_id,ticket_id))");
        jdbc.execute("CREATE TABLE messages(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("""
                CREATE TABLE chat_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT,sender TEXT,message TEXT,timestamp TIMESTAMPTZ,ticket_id TEXT,message_type TEXT,
                    attachment TEXT,channel_id BIGINT,tg_message_id BIGINT,reply_to_tg_id BIGINT)
                """);
        jdbc.execute("""
                CREATE TABLE chat_attachment_metadata(
                    chat_history_id BIGINT UNIQUE REFERENCES chat_history(id),ticket_id TEXT,channel_id BIGINT,
                    storage_key TEXT,storage_provider TEXT,storage_class TEXT,original_name TEXT,mime_type TEXT,size BIGINT,
                    content_hash TEXT,legacy_attachment_ref TEXT,normalization_status TEXT,availability_status TEXT,
                    created_at TIMESTAMPTZ,updated_at TIMESTAMPTZ,archived_at TIMESTAMPTZ,deleted_at TIMESTAMPTZ)
                """);
        jdbc.execute("CREATE TABLE ticket_active(ticket_id TEXT PRIMARY KEY,user_identity TEXT,last_seen TIMESTAMPTZ)");
        jdbc.execute("CREATE TABLE web_form_sessions(ticket_id TEXT)");
        jdbc.update("INSERT INTO tickets VALUES (42,?,77)", owner);
        jdbc.update("INSERT INTO messages(user_id,ticket_id,channel_id) VALUES (42,?,77)", owner);
        if (!owner.equals(owner.trim())) {
            jdbc.update("INSERT INTO tickets VALUES (88,?,88)", owner.trim());
            jdbc.update("INSERT INTO messages(user_id,ticket_id,channel_id) VALUES (88,?,88)", owner.trim());
        }
        var storage = mock(AttachmentObjectStorageService.class);
        when(storage.providerLabel()).thenReturn("local_fs");
        var metadata = spy(new ChatAttachmentMetadataService(jdbc, storage));
        JdbcTemplate targetJdbc = jdbc;
        if (failedTargetLookup) {
            targetJdbc = spy(jdbc);
            doAnswer(call -> {
                String sql = call.getArgument(0);
                if (sql.contains("AND user_id") && sql.contains("AND channel_id")) {
                    throw new DataAccessResourceFailureException("target lookup unavailable");
                }
                return call.callRealMethod();
            }).when(targetJdbc).queryForObject(anyString(), eq(Integer.class), any(Object[].class));
        }
        var targets = spy(new DialogReplyTargetService(targetJdbc, metadata, new LegacyTicketIdJdbcGuard(jdbc)));
        return new Fixture(jdbc, targets, metadata, storage);
    }

    private void noHistoryOrMetadata(Fixture fixture) {
        assertThat(fixture.jdbc().queryForObject("SELECT COUNT(*) FROM chat_history", Integer.class)).isZero();
        assertThat(fixture.jdbc().queryForObject("SELECT COUNT(*) FROM chat_attachment_metadata", Integer.class)).isZero();
        assertThat(fixture.jdbc().queryForObject("SELECT COUNT(*) FROM ticket_active", Integer.class)).isZero();
        verifyNoInteractions(fixture.metadata(), fixture.storage());
    }

    @ParameterizedTest
    @ValueSource(strings = {"wrong-user", "wrong-channel", "null-target", "null-user", "null-channel",
            "absent-ticket", "duplicate-ticket", "missing-schema"})
    void directOutgoingWritesRequireMatchingCanonicalTupleBeforeAnyInsert(String condition) {
        Fixture fixture = fixture("T", false);
        DialogReplyTarget target = switch (condition) {
            case "wrong-user" -> new DialogReplyTarget(99L, 77L);
            case "wrong-channel" -> new DialogReplyTarget(42L, 88L);
            case "null-target" -> null;
            case "null-user" -> new DialogReplyTarget(null, 77L);
            case "null-channel" -> new DialogReplyTarget(42L, null);
            default -> new DialogReplyTarget(42L, 77L);
        };
        if ("absent-ticket".equals(condition)) fixture.jdbc().execute("DELETE FROM tickets");
        if ("duplicate-ticket".equals(condition)) fixture.jdbc().update("INSERT INTO tickets VALUES (99,'T',77)");
        if ("missing-schema".equals(condition)) fixture.jdbc().execute("DROP TABLE tickets");

        assertThatThrownBy(() -> fixture.targets().logOutgoingMessage(target, "T", "reply", "text", 1L, null, "operator"))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> fixture.targets().logOutgoingMediaMessage(
                target, "T", "caption", "stored.png", "photo.png", "image/png", 3L, "image", 1L, null))
                .isInstanceOf(IllegalArgumentException.class);
        noHistoryOrMetadata(fixture);
    }

    static Stream<Arguments> rejectedPreflights() {
        return Stream.of("wrong-user", "wrong-channel", "duplicate", "changed-channel", "lookup-failure")
                .flatMap(condition -> Stream.of("text", "media", "web").map(kind -> Arguments.of(condition, kind)));
    }

    @ParameterizedTest
    @MethodSource("rejectedPreflights")
    void staleOrForgedRecipientStopsBeforeTransportLedgerAndPersistence(String condition, String kind) {
        Fixture fixture = fixture("T", "lookup-failure".equals(condition));
        DialogReplyTarget target = new DialogReplyTarget("wrong-user".equals(condition) ? 99L : 42L,
                "wrong-channel".equals(condition) ? 88L : 77L);
        doReturn(Optional.of(target)).when(fixture.targets()).loadReplyTarget("T");
        if ("duplicate".equals(condition)) fixture.jdbc().update("INSERT INTO tickets VALUES (99,'T',77)");
        if ("changed-channel".equals(condition)) fixture.jdbc().update("UPDATE tickets SET channel_id=88 WHERE ticket_id='T'");
        if ("web".equals(kind)) fixture.jdbc().update("INSERT INTO web_form_sessions VALUES ('T')");
        var transport = mock(DialogReplyTransportService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        Channel channel = new Channel();
        channel.setId(target.channelId()); channel.setPlatform("telegram"); channel.setToken("controlled-token");
        when(transport.loadChannel(target.channelId())).thenReturn(Optional.of(channel));
        when(transport.sendText(channel, target.userId(), "reply", 1L))
                .thenReturn(new DialogReplyTransportService.DialogReplyTransportResult(null, 90L));
        var file = new MockMultipartFile("file", "photo.png", "image/png", new byte[] {1, 2, 3});
        when(transport.sendMedia(channel, target.userId(), file, "caption", "photo.png", 1L))
                .thenReturn(new DialogReplyTransportService.DialogReplyTransportResult(null, 91L));
        var replies = new DialogReplyService(fixture.targets(), transport, responsibility, ledger);

        if ("media".equals(kind)) {
            var result = replies.sendMediaReply("T", file, "caption", 1L, "operator",
                    "stored.png", "photo.png", "image/png", 3L);
            assertThat(result.success()).isFalse();
            assertThat(result.error()).isEqualTo("Не удалось определить получателя сообщения.");
        } else {
            var result = replies.sendReply("T", "reply", 1L, "operator");
            assertThat(result.success()).isFalse();
            assertThat(result.error()).isEqualTo("Не удалось определить получателя сообщения.");
        }
        verifyNoInteractions(transport, ledger, responsibility);
        noHistoryOrMetadata(fixture);
    }

    @ParameterizedTest
    @ValueSource(strings = {"T", " T ", "T/100", " T/100?&%#+ Ю ", "T%2F+", " null "})
    void exactOwnerPreservesTextAndMediaTransportAndBothPersistedTuples(String owner) {
        Fixture fixture = fixture(owner, false);
        var transport = mock(DialogReplyTransportService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        Channel channel = new Channel();
        channel.setId(77L); channel.setPlatform("telegram"); channel.setToken("controlled-token");
        when(transport.loadChannel(77L)).thenReturn(Optional.of(channel));
        when(transport.sendText(channel, 42L, "reply", 1L))
                .thenReturn(new DialogReplyTransportService.DialogReplyTransportResult(null, 90L));
        var file = new MockMultipartFile("file", "photo.png", "image/png", new byte[] {1, 2, 3});
        when(transport.sendMedia(channel, 42L, file, "caption", "photo.png", 1L))
                .thenReturn(new DialogReplyTransportService.DialogReplyTransportResult(null, 91L));
        when(responsibility.assignResponsibleIfMissing(owner, "operator")).thenReturn("operator");
        var replies = new DialogReplyService(fixture.targets(), transport, responsibility, ledger);

        assertThat(replies.sendReply(owner, "reply", 1L, "operator", "ai_agent").success()).isTrue();
        assertThat(replies.sendMediaReply(owner, file, "caption", 1L, "operator",
                "stored.png", "photo.png", "image/png", 3L).success()).isTrue();

        var rows = fixture.jdbc().queryForList("SELECT user_id,ticket_id,channel_id FROM chat_history ORDER BY id");
        assertThat(rows).hasSize(2).allSatisfy(row -> {
            assertThat(row.get("user_id")).isEqualTo(42L);
            assertThat(row.get("ticket_id")).isEqualTo(owner);
            assertThat(row.get("channel_id")).isEqualTo(77L);
        });
        var metadata = fixture.jdbc().queryForMap("SELECT ticket_id,channel_id,storage_class FROM chat_attachment_metadata");
        assertThat(metadata.get("ticket_id")).isEqualTo(owner);
        assertThat(metadata.get("channel_id")).isEqualTo(77L);
        assertThat(metadata.get("storage_class")).isEqualTo("dialog_attachment");
        verify(transport).sendText(channel, 42L, "reply", 1L);
        verify(transport).sendMedia(channel, 42L, file, "caption", "photo.png", 1L);
        verify(ledger).recordAttempt(eq(channel), eq(owner), eq(42L), eq("ai_agent"), eq("text"), eq(1L), any());
        verify(ledger).recordAttempt(eq(channel), eq(owner), eq(42L), eq("operator"), eq("image"), eq(1L), any());
    }

    @Test
    void validWebFormReplyRemainsLocalAndKeepsExactOwner() {
        Fixture fixture = fixture(" T ", false);
        fixture.jdbc().update("INSERT INTO web_form_sessions VALUES (' T ')");
        var transport = mock(DialogReplyTransportService.class);
        Channel channel = new Channel(); channel.setId(77L);
        when(transport.loadChannel(77L)).thenReturn(Optional.of(channel));
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        var replies = new DialogReplyService(fixture.targets(), transport, responsibility, ledger);

        assertThat(replies.sendReply(" T ", "reply", null, "operator").success()).isTrue();

        assertThat(fixture.jdbc().queryForObject("SELECT ticket_id FROM chat_history", String.class)).isEqualTo(" T ");
        verify(transport, org.mockito.Mockito.never()).sendText(any(), any(), any(), any());
        verifyNoInteractions(ledger, fixture.metadata(), fixture.storage());
    }
}
