class DialogOperatorConditionalMutationPostgresqlTest {
    private record Fixture(JdbcTemplate jdbc, LegacyTicketIdJdbcGuard guard,
                           DialogReplyTargetService targets, ChatAttachmentMetadataService metadata) { }

    private Fixture fixture(String owner) {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplate("operator_conditional_mutation");
        jdbc.execute("CREATE TABLE tickets(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,PRIMARY KEY(user_id,ticket_id))");
        jdbc.execute("CREATE TABLE messages(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("""
                CREATE TABLE chat_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT,ticket_id TEXT,channel_id BIGINT,tg_message_id BIGINT,sender TEXT,
                    message TEXT,original_message TEXT,edited_at TIMESTAMPTZ,deleted_at TIMESTAMPTZ,
                    attachment TEXT,message_type TEXT,reply_to_tg_id BIGINT)
                """);
        jdbc.execute("CREATE TABLE web_form_sessions(ticket_id TEXT)");
        jdbc.update("INSERT INTO tickets VALUES (42,?,77)", owner);
        jdbc.update("INSERT INTO messages(user_id,ticket_id,channel_id) VALUES (42,?,77)", owner);
        history(jdbc, owner, 42L, 77L, "operator");
        var guard = spy(new LegacyTicketIdJdbcGuard(jdbc));
        var metadata = mock(ChatAttachmentMetadataService.class);
        return new Fixture(jdbc, guard, new DialogReplyTargetService(jdbc, metadata, guard), metadata);
    }

    private void history(JdbcTemplate jdbc, String owner, long user, long channel, String sender) {
        jdbc.update("""
                INSERT INTO chat_history(user_id,ticket_id,channel_id,tg_message_id,sender,message,
                    attachment,message_type,reply_to_tg_id)
                VALUES (?,?,?,900,?,'before','stored.png','image',800)
                """, user, owner, channel, sender);
    }

    private List<Map<String, Object>> rows(Fixture fixture) {
        return fixture.jdbc().queryForList("SELECT * FROM chat_history ORDER BY id");
    }

    private int mutate(Fixture fixture, String action, String owner, Long providerId) {
        return "edit".equals(action)
                ? fixture.targets().markOperatorMessageEdited(owner, providerId, "after")
                : fixture.targets().markOperatorMessageDeleted(owner, providerId);
    }

    private void introduceChange(Fixture fixture, String condition) {
        switch (condition) {
            case "duplicate-history" -> history(fixture.jdbc(), "T", 42L, 77L, "operator");
            case "duplicate-ticket" -> fixture.jdbc().execute("INSERT INTO tickets VALUES (99,'T',88)");
            case "changed-channel" -> fixture.jdbc().execute("UPDATE tickets SET channel_id=88");
            default -> throw new IllegalArgumentException(condition);
        }
    }

    static Stream<Arguments> directCases() {
        return Stream.of("valid", "duplicate-history", "absent-message", "wrong-user", "wrong-channel",
                        "non-operator", "duplicate-ticket", "missing-ticket", "null-provider-id")
                .flatMap(condition -> Stream.of("edit", "delete").map(action -> Arguments.of(condition, action)));
    }

    @ParameterizedTest
    @MethodSource("directCases")
    void directWriterChangesOnlyOneUnambiguousOwnedOperatorRow(String condition, String action) {
        Fixture fixture = fixture("T");
        switch (condition) {
            case "duplicate-history", "duplicate-ticket" -> introduceChange(fixture, condition);
            case "absent-message" -> fixture.jdbc().execute("UPDATE chat_history SET tg_message_id=901");
            case "wrong-user" -> fixture.jdbc().execute("UPDATE chat_history SET user_id=99");
            case "wrong-channel" -> fixture.jdbc().execute("UPDATE chat_history SET channel_id=88");
            case "non-operator" -> fixture.jdbc().execute("UPDATE chat_history SET sender='ai_agent'");
            case "missing-ticket" -> fixture.jdbc().execute("DELETE FROM tickets");
            default -> { }
        }
        List<Map<String, Object>> before = rows(fixture);

        int updated = mutate(fixture, action, "T", "null-provider-id".equals(condition) ? null : 900L);

        assertThat(updated).isEqualTo("valid".equals(condition) ? 1 : 0);
        if (!"valid".equals(condition)) assertThat(rows(fixture)).isEqualTo(before);
        verifyNoInteractions(fixture.metadata());
    }

    static Stream<Arguments> changesAfterGuard() {
        return Stream.of("duplicate-history", "duplicate-ticket")
                .flatMap(condition -> Stream.of("edit", "delete").map(action -> Arguments.of(condition, action)));
    }

    @ParameterizedTest
    @MethodSource("changesAfterGuard")
    void updateRechecksAmbiguityVisibleAfterLegacyGuard(String condition, String action) {
        Fixture fixture = fixture("T");
        var changed = new AtomicBoolean();
        var beforeUpdate = new AtomicReference<List<Map<String, Object>>>();
        doAnswer(call -> {
            boolean allowed = (boolean) call.callRealMethod();
            if (allowed && changed.compareAndSet(false, true)) {
                // Controlled committed interleaving before the UPDATE statement snapshot.
                introduceChange(fixture, condition);
                beforeUpdate.set(rows(fixture));
            }
            return allowed;
        }).when(fixture.guard()).hasUniqueTicket("T");

        assertThat(mutate(fixture, action, "T", 900L)).isZero();

        assertThat(changed).isTrue();
        assertThat(rows(fixture)).isEqualTo(beforeUpdate.get());
        verifyNoInteractions(fixture.metadata());
    }

    static Stream<Arguments> exactCases() {
        return Stream.of("T", " T ", "T/100", " T/100?&%#+ Ю ", "T%2F+", " null ")
                .flatMap(owner -> Stream.of("edit", "delete").map(action -> Arguments.of(owner, action)));
    }

    @ParameterizedTest
    @MethodSource("exactCases")
    void validExactIdentityPreservesNeighborsFieldsAndRepeatedMutationSemantics(String owner, String action) {
        Fixture fixture = fixture(owner);
        history(fixture.jdbc(), owner, 99L, 88L, "operator");
        history(fixture.jdbc(), owner, 42L, 77L, "ai_agent");
        if (!owner.equals(owner.trim())) {
            fixture.jdbc().update("INSERT INTO tickets VALUES (88,?,88)", owner.trim());
            history(fixture.jdbc(), owner.trim(), 88L, 88L, "operator");
        }
        List<Map<String, Object>> neighbors = fixture.jdbc().queryForList("SELECT * FROM chat_history WHERE id<>1 ORDER BY id");

        assertThat(mutate(fixture, action, owner, 900L)).isEqualTo(1);
        assertThat(mutate(fixture, action, owner, 900L)).isEqualTo(1);

        Map<String, Object> row = fixture.jdbc().queryForMap("SELECT * FROM chat_history WHERE id=1");
        assertThat(row.get("ticket_id")).isEqualTo(owner);
        assertThat(row.get("user_id")).isEqualTo(42L);
        assertThat(row.get("channel_id")).isEqualTo(77L);
        assertThat(row.get("attachment")).isEqualTo("stored.png");
        assertThat(row.get("message_type")).isEqualTo("image");
        assertThat(row.get("reply_to_tg_id")).isEqualTo(800L);
        if ("edit".equals(action)) {
            assertThat(row.get("message")).isEqualTo("after");
            assertThat(row.get("original_message")).isEqualTo("before");
            assertThat(row.get("edited_at")).isNotNull();
            assertThat(row.get("deleted_at")).isNull();
        } else {
            assertThat(row.get("message")).isEqualTo("before");
            assertThat(row.get("original_message")).isNull();
            assertThat(row.get("edited_at")).isNull();
            assertThat(row.get("deleted_at")).isNotNull();
        }
        assertThat(fixture.jdbc().queryForList("SELECT * FROM chat_history WHERE id<>1 ORDER BY id")).isEqualTo(neighbors);
        verifyNoInteractions(fixture.metadata());
    }

    static Stream<Arguments> changesAfterPreflight() {
        return Stream.of("duplicate-history", "duplicate-ticket", "changed-channel")
                .flatMap(condition -> Stream.of("edit", "delete")
                        .flatMap(action -> Stream.of(false, true)
                                .map(web -> Arguments.of(condition, action, web))));
    }

    @ParameterizedTest
    @MethodSource("changesAfterPreflight")
    void lateChangeAfterPreflightDoesNotMutateHistoryOrAssignResponsibility(
            String condition, String action, boolean web) {
        Fixture fixture = fixture("T");
        var targets = spy(fixture.targets());
        var beforeUpdate = new AtomicReference<List<Map<String, Object>>>();
        if (web) {
            fixture.jdbc().execute("INSERT INTO web_form_sessions VALUES ('T')");
            doAnswer(call -> {
                boolean session = (boolean) call.callRealMethod();
                introduceChange(fixture, condition);
                beforeUpdate.set(rows(fixture));
                return session;
            }).when(targets).hasWebFormSession("T");
        }
        var transport = mock(DialogReplyTransportService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        Channel channel = new Channel();
        channel.setId(77L); channel.setPlatform("telegram"); channel.setToken("controlled-token");
        when(transport.loadChannel(77L)).thenReturn(Optional.of(channel));
        org.mockito.stubbing.Answer<DialogReplyTransportService.DialogReplyTransportResult> provider = call -> {
            introduceChange(fixture, condition);
            beforeUpdate.set(rows(fixture));
            return DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L);
        };
        doAnswer(provider).when(transport).editTelegramMessage(channel, 42L, 900L, "after");
        doAnswer(provider).when(transport).deleteTelegramMessage(channel, 42L, 900L);
        var replies = new DialogReplyService(targets, transport, responsibility, ledger);

        var result = "edit".equals(action)
                ? replies.editOperatorMessage("T", 900L, "after", "operator")
                : replies.deleteOperatorMessage("T", 900L, "operator");

        assertThat(result.success()).isFalse();
        assertThat(result.error()).isEqualTo("Сообщение оператора не найдено.");
        assertThat(beforeUpdate.get()).isNotNull();
        assertThat(rows(fixture)).isEqualTo(beforeUpdate.get());
        verifyNoInteractions(responsibility, fixture.metadata());
        if (web) {
            verifyNoInteractions(ledger);
        } else {
            verify(ledger).recordAttempt(eq(channel), eq("T"), eq(42L), eq("operator"),
                    eq("edit".equals(action) ? "text_edit" : "message_delete"), eq(null), any());
        }
    }
}
