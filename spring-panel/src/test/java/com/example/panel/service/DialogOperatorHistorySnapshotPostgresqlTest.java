package com.example.panel.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.doAnswer;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.spy;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

import com.example.panel.entity.Channel;
import com.example.panel.support.PostgresqlJdbcTestSupport;
import java.util.Optional;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.jdbc.core.JdbcTemplate;

class DialogOperatorHistorySnapshotPostgresqlTest {
    private record Fixture(JdbcTemplate jdbc, DialogReplyTargetService targets,
                           ChatAttachmentMetadataService metadata) { }

    private Fixture fixture(String owner) {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplateDefaultStringType("operator_history_snapshot");
        jdbc.execute("CREATE TABLE tickets(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,PRIMARY KEY(user_id,ticket_id))");
        jdbc.execute("CREATE TABLE messages(user_id BIGINT,ticket_id TEXT UNIQUE,channel_id BIGINT,created_at TIMESTAMPTZ)");
        jdbc.execute("""
                CREATE TABLE chat_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT,ticket_id TEXT,channel_id BIGINT,tg_message_id BIGINT,sender TEXT,
                    message TEXT,original_message TEXT,edited_at TIMESTAMPTZ,deleted_at TIMESTAMPTZ,
                    attachment TEXT,message_type TEXT,reply_to_tg_id BIGINT,timestamp TIMESTAMPTZ)
                """);
        jdbc.execute("CREATE TABLE web_form_sessions(ticket_id TEXT)");
        jdbc.execute("CREATE TABLE ticket_active(ticket_id TEXT,user_identity TEXT,last_seen TIMESTAMPTZ)");
        jdbc.update("INSERT INTO tickets VALUES (42,?,77)", owner);
        jdbc.update("INSERT INTO messages VALUES (42,?,77,CURRENT_TIMESTAMP)", owner);
        history(jdbc, owner, 42L, 77L, "operator");
        if (!owner.equals(owner.trim())) {
            jdbc.update("INSERT INTO tickets VALUES (88,?,88)", owner.trim());
            jdbc.update("INSERT INTO messages VALUES (88,?,88,CURRENT_TIMESTAMP)", owner.trim());
            history(jdbc, owner.trim(), 88L, 88L, "operator");
        }
        var metadata = mock(ChatAttachmentMetadataService.class);
        return new Fixture(jdbc, spy(new DialogReplyTargetService(jdbc, metadata, new LegacyTicketIdJdbcGuard(jdbc))), metadata);
    }

    private void history(JdbcTemplate jdbc, String owner, long user, long channel, String sender) {
        jdbc.update("""
                INSERT INTO chat_history(user_id,ticket_id,channel_id,tg_message_id,sender,message,attachment,message_type)
                VALUES (?,?,?,900,?,'before','stored.png','image')
                """, user, owner, channel, sender);
    }

    private AtomicInteger changeAfterOwnerProof(Fixture fixture, String owner, String condition) {
        var proofs = new AtomicInteger();
        doAnswer(call -> {
            boolean allowed = (boolean) call.callRealMethod();
            assertThat(allowed).as("real owner proof before committed change").isTrue();
            proofs.incrementAndGet();
            switch (condition) {
                case "duplicate" -> fixture.jdbc().update("INSERT INTO tickets VALUES (99,?,99)", owner);
                case "missing" -> fixture.jdbc().update("DELETE FROM tickets WHERE ticket_id=?", owner);
                case "user" -> fixture.jdbc().update("UPDATE tickets SET user_id=99 WHERE ticket_id=?", owner);
                case "channel" -> fixture.jdbc().update("UPDATE tickets SET channel_id=99 WHERE ticket_id=?", owner);
                case "both" -> fixture.jdbc().update("UPDATE tickets SET user_id=99,channel_id=99 WHERE ticket_id=?", owner);
                default -> throw new IllegalArgumentException(condition);
            }
            // The next history SELECT sees this committed change, not the earlier owner proof.
            return allowed;
        }).when(fixture.targets()).hasReplyTargetOwner(eq(owner), eq(new DialogReplyTarget(42L, 77L)));
        return proofs;
    }

    static Stream<Arguments> lateParents() {
        return Stream.of("T", " T ").flatMap(owner -> Stream.of("duplicate", "missing", "user", "channel", "both")
                .map(condition -> Arguments.of(owner, condition)));
    }

    @ParameterizedTest
    @MethodSource("lateParents")
    void staleOwnerProofCannotAuthorizeAnOperatorHistoryRow(String owner, String condition) {
        Fixture fixture = fixture(owner);
        var before = fixture.jdbc().queryForList("SELECT * FROM chat_history ORDER BY id");
        AtomicInteger proofs = changeAfterOwnerProof(fixture, owner, condition);

        assertThat(fixture.targets().hasOperatorMessageOwner(owner, new DialogReplyTarget(42L, 77L), 900L)).isFalse();

        assertThat(proofs).hasValue(1);
        assertThat(fixture.jdbc().queryForList("SELECT * FROM chat_history ORDER BY id")).isEqualTo(before);
        verifyNoInteractions(fixture.metadata());
    }

    static Stream<Arguments> lateActions() {
        return lateParents().flatMap(parent -> Stream.of("edit", "delete").flatMap(action -> Stream.of(false, true)
                .map(web -> Arguments.of(parent.get()[0], parent.get()[1], action, web))));
    }

    @ParameterizedTest
    @MethodSource("lateActions")
    void lateParentChangeStopsProviderAndWebActionsBeforeChannelLookup(
            String owner, String condition, String action, boolean web) {
        Fixture fixture = fixture(owner);
        if (web) fixture.jdbc().update("INSERT INTO web_form_sessions VALUES (?)", owner);
        var before = fixture.jdbc().queryForList("SELECT * FROM chat_history ORDER BY id");
        AtomicInteger proofs = changeAfterOwnerProof(fixture, owner, condition);
        var transport = mock(DialogReplyTransportService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        Channel channel = new Channel();
        channel.setId(77L); channel.setPlatform("telegram"); channel.setToken("controlled-token");
        when(transport.loadChannel(77L)).thenReturn(Optional.of(channel));
        when(transport.editTelegramMessage(channel, 42L, 900L, "after"))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        when(transport.deleteTelegramMessage(channel, 42L, 900L))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        var replies = new DialogReplyService(fixture.targets(), transport, responsibility, ledger);

        var result = "edit".equals(action) ? replies.editOperatorMessage(owner, 900L, "after", "operator")
                : replies.deleteOperatorMessage(owner, 900L, "operator");

        assertThat(result).isEqualTo(DialogReplyService.DialogReplyResult.error("Сообщение оператора не найдено."));
        verifyNoInteractions(transport, responsibility, ledger, fixture.metadata());
        assertThat(proofs).hasValue(1);
        assertThat(fixture.jdbc().queryForList("SELECT * FROM chat_history ORDER BY id")).isEqualTo(before);
        assertThat(fixture.jdbc().queryForObject("SELECT COUNT(*) FROM ticket_active", Integer.class)).isZero();
    }

    @ParameterizedTest
    @ValueSource(strings = {"T", " T ", "T/100", " T/100?&%#+ Ю ", "T%2F+", " null "})
    void exactCanonicalOperatorHistoryKeepsIdentityAndIgnoresForeignRows(String owner) {
        Fixture fixture = fixture(owner);
        history(fixture.jdbc(), owner, 99L, 99L, "operator");
        history(fixture.jdbc(), owner, 42L, 77L, "ai_agent");
        var before = fixture.jdbc().queryForList("SELECT * FROM chat_history ORDER BY id");

        assertThat(fixture.targets().hasOperatorMessageOwner(owner, new DialogReplyTarget(42L, 77L), 900L)).isTrue();
        assertThat(fixture.targets().hasOperatorMessageOwner(owner, new DialogReplyTarget(99L, 99L), 900L)).isFalse();
        if (!owner.equals(owner.trim())) {
            assertThat(fixture.targets().hasOperatorMessageOwner(owner.trim(), new DialogReplyTarget(88L, 88L), 900L)).isTrue();
        }

        assertThat(fixture.jdbc().queryForList("SELECT * FROM chat_history ORDER BY id")).isEqualTo(before);
        verifyNoInteractions(fixture.metadata());
    }

    @ParameterizedTest
    @ValueSource(strings = {"user", "channel", "sender", "duplicate"})
    void unownedOrDuplicateHistoryStillFailsClosed(String condition) {
        Fixture fixture = fixture("T");
        switch (condition) {
            case "user" -> fixture.jdbc().execute("UPDATE chat_history SET user_id=99");
            case "channel" -> fixture.jdbc().execute("UPDATE chat_history SET channel_id=99");
            case "sender" -> fixture.jdbc().execute("UPDATE chat_history SET sender='ai_agent'");
            case "duplicate" -> history(fixture.jdbc(), "T", 42L, 77L, "operator");
            default -> throw new IllegalArgumentException(condition);
        }

        assertThat(fixture.targets().hasOperatorMessageOwner("T", new DialogReplyTarget(42L, 77L), 900L)).isFalse();
        verifyNoInteractions(fixture.metadata());
    }

    @Test
    void nullProviderIdStillStopsBeforeOwnerProof() {
        Fixture fixture = fixture("T");
        assertThat(fixture.targets().hasOperatorMessageOwner("T", new DialogReplyTarget(42L, 77L), null)).isFalse();
        verifyNoInteractions(fixture.metadata());
    }

    @Test
    void unavailableHistoryStillFailsClosed() {
        Fixture fixture = fixture("T");
        fixture.jdbc().execute("DROP TABLE chat_history");
        assertThat(fixture.targets().hasOperatorMessageOwner("T", new DialogReplyTarget(42L, 77L), 900L)).isFalse();
        verifyNoInteractions(fixture.metadata());
    }
}
