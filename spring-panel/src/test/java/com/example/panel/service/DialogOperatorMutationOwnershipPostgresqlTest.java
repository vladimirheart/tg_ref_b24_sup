class DialogOperatorMutationOwnershipPostgresqlTest {
    private record Fixture(JdbcTemplate jdbc, DialogReplyTargetService targets,
                           ChatAttachmentMetadataService metadata) { }

    private Fixture fixture(String owner, boolean failedHistoryLookup) {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplate("operator_mutation_owner");
        jdbc.execute("CREATE TABLE tickets(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,PRIMARY KEY(user_id,ticket_id))");
        jdbc.execute("CREATE TABLE messages(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("""
                CREATE TABLE chat_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT,ticket_id TEXT,channel_id BIGINT,tg_message_id BIGINT,sender TEXT,
                    message TEXT,original_message TEXT,edited_at TIMESTAMPTZ,deleted_at TIMESTAMPTZ,
                    attachment TEXT,message_type TEXT,reply_to_tg_id BIGINT)
                """);
        jdbc.execute("CREATE TABLE web_form_sessions(ticket_id TEXT)");
        jdbc.update("INSERT INTO tickets VALUES (42,?,77)", owner);
        jdbc.update("INSERT INTO messages(user_id,ticket_id,channel_id) VALUES (42,?,77)", owner);
        history(jdbc, owner, 42L, 77L, "operator");
        if (!owner.equals(owner.trim())) {
            jdbc.update("INSERT INTO tickets VALUES (88,?,88)", owner.trim());
            jdbc.update("INSERT INTO messages(user_id,ticket_id,channel_id) VALUES (88,?,88)", owner.trim());
            history(jdbc, owner.trim(), 88L, 88L, "operator");
        }
        var metadata = mock(ChatAttachmentMetadataService.class);
        JdbcTemplate targetJdbc = jdbc;
        if (failedHistoryLookup) {
            targetJdbc = spy(jdbc);
            doAnswer(call -> {
                String sql = call.getArgument(0);
                if (sql.contains("FROM chat_history") && sql.contains("AND user_id = ?")
                        && sql.contains("AND channel_id = ?")) {
                    throw new DataAccessResourceFailureException("history lookup unavailable");
                }
                return call.callRealMethod();
            }).when(targetJdbc).queryForObject(anyString(), eq(Integer.class), any(Object[].class));
        }
        return new Fixture(jdbc,
                spy(new DialogReplyTargetService(targetJdbc, metadata, new LegacyTicketIdJdbcGuard(jdbc))), metadata);
    }

    private void history(JdbcTemplate jdbc, String ticket, long user, long channel, String sender) {
        jdbc.update("""
                INSERT INTO chat_history(user_id,ticket_id,channel_id,tg_message_id,sender,message,
                    attachment,message_type,reply_to_tg_id)
                VALUES (?,?,?,900,?,'before','stored.png','image',800)
                """, user, ticket, channel, sender);
    }

    static Stream<Arguments> deniedMutations() {
        return Stream.of("wrong-history-user", "wrong-history-channel", "other-ticket", "absent-message",
                        "non-operator", "duplicate-message", "duplicate-ticket", "wrong-target-user",
                        "wrong-target-channel", "changed-channel", "lookup-failure", "missing-history-schema")
                .flatMap(condition -> Stream.of("edit", "delete")
                        .flatMap(action -> Stream.of(false, true)
                                .map(web -> Arguments.of(condition, action, web))));
    }

    @ParameterizedTest
    @MethodSource("deniedMutations")
    void unownedOrAmbiguousOperatorMessageStopsBeforeExternalOrLocalMutation(
            String condition, String action, boolean web) {
        Fixture fixture = fixture("T", "lookup-failure".equals(condition));
        JdbcTemplate jdbc = fixture.jdbc();
        switch (condition) {
            case "wrong-history-user" -> jdbc.execute("UPDATE chat_history SET user_id=99");
            case "wrong-history-channel" -> jdbc.execute("UPDATE chat_history SET channel_id=88");
            case "other-ticket" -> jdbc.execute("UPDATE chat_history SET ticket_id='OTHER'");
            case "absent-message" -> jdbc.execute("UPDATE chat_history SET tg_message_id=901");
            case "non-operator" -> jdbc.execute("UPDATE chat_history SET sender='ai_agent'");
            case "duplicate-message" -> history(jdbc, "T", 42L, 77L, "operator");
            case "duplicate-ticket" -> jdbc.execute("INSERT INTO tickets VALUES (99,'T',77)");
            case "changed-channel" -> jdbc.execute("UPDATE tickets SET channel_id=88");
            case "missing-history-schema" -> jdbc.execute("ALTER TABLE chat_history RENAME TO saved_history");
            default -> { }
        }
        String historyTable = "missing-history-schema".equals(condition) ? "saved_history" : "chat_history";
        List<Map<String, Object>> before = jdbc.queryForList("SELECT * FROM " + historyTable + " ORDER BY id");
        DialogReplyTarget candidate = new DialogReplyTarget(
                "wrong-target-user".equals(condition) ? 99L : 42L,
                "wrong-target-channel".equals(condition) ? 88L : 77L);
        doReturn(Optional.of(candidate)).when(fixture.targets()).loadReplyTarget("T");
        if (web) jdbc.execute("INSERT INTO web_form_sessions VALUES ('T')");
        var transport = mock(DialogReplyTransportService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        Channel channel = new Channel();
        channel.setId(candidate.channelId()); channel.setPlatform("telegram"); channel.setToken("controlled-token");
        when(transport.loadChannel(candidate.channelId())).thenReturn(Optional.of(channel));
        when(transport.editTelegramMessage(channel, candidate.userId(), 900L, "after"))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        when(transport.deleteTelegramMessage(channel, candidate.userId(), 900L))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        var replies = new DialogReplyService(fixture.targets(), transport, responsibility, ledger);

        var result = "edit".equals(action)
                ? replies.editOperatorMessage("T", 900L, "after", "operator")
                : replies.deleteOperatorMessage("T", 900L, "operator");

        assertThat(result.success()).isFalse();
        assertThat(result.error()).isEqualTo("Сообщение оператора не найдено.");
        verifyNoInteractions(transport, ledger, responsibility, fixture.metadata());
        verify(fixture.targets(), never()).markOperatorMessageEdited(anyString(), any(), anyString());
        verify(fixture.targets(), never()).markOperatorMessageDeleted(anyString(), any());
        assertThat(jdbc.queryForList("SELECT * FROM " + historyTable + " ORDER BY id")).isEqualTo(before);
    }

    static Stream<Arguments> validMutations() {
        return Stream.of("T", " T ", "T/100", " T/100?&%#+ Ю ", "T%2F+", " null ")
                .flatMap(owner -> Stream.of("edit", "delete")
                        .flatMap(action -> Stream.of(false, true)
                                .map(web -> Arguments.of(owner, action, web))));
    }

    @ParameterizedTest
    @MethodSource("validMutations")
    void exactOwnedMessageKeepsTransportArgsLocalFlowAndHistoryFields(String owner, String action, boolean web) {
        Fixture fixture = fixture(owner, false);
        JdbcTemplate jdbc = fixture.jdbc();
        // Same provider ID on a foreign tuple must not be edited/deleted or create ambiguity.
        history(jdbc, owner, 99L, 88L, "operator");
        history(jdbc, owner, 42L, 77L, "ai_agent");
        List<Map<String, Object>> otherRows = jdbc.queryForList("""
                SELECT * FROM chat_history WHERE NOT (ticket_id=? AND user_id=42 AND channel_id=77 AND sender='operator')
                ORDER BY id
                """, owner);
        if (web) jdbc.update("INSERT INTO web_form_sessions VALUES (?)", owner);
        var transport = mock(DialogReplyTransportService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        Channel channel = new Channel();
        channel.setId(77L); channel.setPlatform("telegram"); channel.setToken("controlled-token");
        when(transport.loadChannel(77L)).thenReturn(Optional.of(channel));
        when(transport.editTelegramMessage(channel, 42L, 900L, "after"))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        when(transport.deleteTelegramMessage(channel, 42L, 900L))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        when(responsibility.assignResponsibleIfMissing(owner, "operator")).thenReturn("operator");
        var replies = new DialogReplyService(fixture.targets(), transport, responsibility, ledger);

        var result = "edit".equals(action)
                ? replies.editOperatorMessage(owner, 900L, "after", "operator")
                : replies.deleteOperatorMessage(owner, 900L, "operator");

        assertThat(result.success()).isTrue();
        assertThat(result.error()).isNull();
        assertThat(result.telegramMessageId()).isEqualTo(900L);
        assertThat(result.responsible()).isEqualTo("operator");
        assertThat(result.timestamp()).isNotBlank();
        Map<String, Object> row = jdbc.queryForMap("""
                SELECT * FROM chat_history WHERE ticket_id=? AND user_id=42 AND channel_id=77 AND sender='operator'
                """, owner);
        assertThat(row.get("ticket_id")).isEqualTo(owner);
        assertThat(row.get("user_id")).isEqualTo(42L);
        assertThat(row.get("channel_id")).isEqualTo(77L);
        assertThat(row.get("attachment")).isEqualTo("stored.png");
        assertThat(row.get("message_type")).isEqualTo("image");
        assertThat(row.get("reply_to_tg_id")).isEqualTo(800L);
        if ("edit".equals(action)) {
            assertThat(row.get("message")).isEqualTo("after");
            assertThat(row.get("original_message")).isEqualTo("before");
            assertThat(row.get("edited_at")).isNotNull();
            assertThat(row.get("deleted_at")).isNull();
            verify(transport, web ? never() : org.mockito.Mockito.times(1))
                    .editTelegramMessage(channel, 42L, 900L, "after");
        } else {
            assertThat(row.get("message")).isEqualTo("before");
            assertThat(row.get("original_message")).isNull();
            assertThat(row.get("edited_at")).isNull();
            assertThat(row.get("deleted_at")).isNotNull();
            verify(transport, web ? never() : org.mockito.Mockito.times(1))
                    .deleteTelegramMessage(channel, 42L, 900L);
        }
        assertThat(jdbc.queryForList("""
                SELECT * FROM chat_history WHERE NOT (ticket_id=? AND user_id=42 AND channel_id=77 AND sender='operator')
                ORDER BY id
                """, owner)).isEqualTo(otherRows);
        verify(responsibility).assignResponsibleIfMissing(owner, "operator");
        if (web) {
            verifyNoInteractions(ledger);
        } else {
            verify(ledger).recordAttempt(eq(channel), eq(owner), eq(42L), eq("operator"),
                    eq("edit".equals(action) ? "text_edit" : "message_delete"), eq(null), any());
        }
        verifyNoInteractions(fixture.metadata());
    }
}
