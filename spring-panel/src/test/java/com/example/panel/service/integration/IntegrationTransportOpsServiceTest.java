    @Test
    void buildOverviewIncludesRecentManualOperationPressureAndTrendSummary() {
        jdbcTemplate.update("""
                INSERT INTO integration_transport_operation_log(action_type, summary_text, target_type, target_id, ticket_id, result_status, actor, details_json, created_at)
                VALUES ('manual_replay_inbound', 'Manual replay', 'inbound_event', 'evt-1', 'T-1', 'success', 'operator', '{}', CURRENT_TIMESTAMP)
                """);
        service.recordHealthSnapshot(new IntegrationTransportOpsService.TransportHealthSnapshot(1, 0, 0, 120, 0, 0, 1, 1));
        service.recordHealthSnapshot(new IntegrationTransportOpsService.TransportHealthSnapshot(1, 0, 0, 150, 0, 0, 0, 2));
        service.recordHealthSnapshot(new IntegrationTransportOpsService.TransportHealthSnapshot(1, 0, 0, 160, 0, 0, 0, 3));

        Map<String, Object> payload = service.buildOverview();
        Map<?, ?> healthSnapshot = (Map<?, ?>) payload.get("health_snapshot");
        Map<?, ?> trendSummary = (Map<?, ?>) payload.get("trend_summary");
        List<?> alerts = (List<?>) payload.get("alerts");

        assertThat(healthSnapshot.get("recent_manual_operations")).isEqualTo(1L);
        assertThat(trendSummary.get("sustained_pressure")).isEqualTo(true);
        assertThat(alerts.stream().map(item -> String.valueOf(((Map<?, ?>) item).get("key"))).toList())
            .contains("sustained_transport_pressure");
    }

