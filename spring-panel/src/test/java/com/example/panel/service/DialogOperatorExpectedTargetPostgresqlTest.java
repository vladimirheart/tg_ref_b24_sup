    @ParameterizedTest
    @MethodSource("validTargets")
    void unchangedExactTargetPreservesFieldsNeighborsAndTransport(String owner, String action, boolean web) {
        Fixture fixture = fixture(owner);
        List<Map<String, Object>> neighbors = fixture.jdbc().queryForList("SELECT * FROM chat_history WHERE id<>1 ORDER BY id");
        if (web) fixture.jdbc().update("INSERT INTO web_form_sessions VALUES (?)", owner);
        var transport = mock(DialogReplyTransportService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        Channel channel = channel();
        when(transport.loadChannel(77L)).thenReturn(Optional.of(channel));
        when(transport.editTelegramMessage(channel, 42L, 900L, "after"))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        when(transport.deleteTelegramMessage(channel, 42L, 900L))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        when(responsibility.assignResponsibleIfMissing(owner, "operator")).thenReturn("operator");
        var replies = new DialogReplyService(fixture.targets(), transport, responsibility, ledger);

        var result = "edit".equals(action)
                ? replies.editOperatorMessage(owner, 900L, "after", "operator")
                : replies.deleteOperatorMessage(owner, 900L, "operator");

        assertThat(result.success()).isTrue();
        assertThat(result.telegramMessageId()).isEqualTo(900L);
        assertThat(result.responsible()).isEqualTo("operator");
        assertThat(result.timestamp()).isNotBlank();
        Map<String, Object> row = fixture.jdbc().queryForMap("SELECT * FROM chat_history WHERE id=1");
        assertThat(row.get("ticket_id")).isEqualTo(owner);
        assertThat(row.get("user_id")).isEqualTo(42L);
        assertThat(row.get("channel_id")).isEqualTo(77L);
        assertThat(row.get("attachment")).isEqualTo("stored.png");
        assertThat(row.get("message_type")).isEqualTo("image");
        assertThat(row.get("reply_to_tg_id")).isEqualTo(800L);
        if ("edit".equals(action)) {
            assertThat(row.get("message")).isEqualTo("after");
            assertThat(row.get("original_message")).isEqualTo("before");
            assertThat(row.get("edited_at")).isNotNull();
            assertThat(row.get("deleted_at")).isNull();
        } else {
            assertThat(row.get("message")).isEqualTo("before");
            assertThat(row.get("original_message")).isNull();
            assertThat(row.get("edited_at")).isNull();
            assertThat(row.get("deleted_at")).isNotNull();
        }
        assertThat(fixture.jdbc().queryForList("SELECT * FROM chat_history WHERE id<>1 ORDER BY id")).isEqualTo(neighbors);
        verify(responsibility).assignResponsibleIfMissing(owner, "operator");
        if (web) {
            verifyNoInteractions(ledger);
        } else {
            verify(ledger).recordAttempt(eq(channel), eq(owner), eq(42L), eq("operator"),
                    eq("edit".equals(action) ? "text_edit" : "message_delete"), eq(null), any());
        }
        verifyNoInteractions(fixture.metadata());
    }

    @ParameterizedTest
    @org.junit.jupiter.params.provider.ValueSource(strings = {"edit", "delete"})
    void targetAwareWriterAppendsExactTupleBindsWithoutChangingBaseArgumentOrder(String action) {
        JdbcTemplate jdbc = mock(JdbcTemplate.class);
        LegacyTicketIdJdbcGuard guard = mock(LegacyTicketIdJdbcGuard.class);
        ChatAttachmentMetadataService metadata = mock(ChatAttachmentMetadataService.class);
        when(guard.hasUniqueTicket(" T-EXACT ")).thenReturn(true);
        when(jdbc.update(any(String.class), any(Object[].class))).thenReturn(1);
        var targets = new DialogReplyTargetService(jdbc, metadata, guard);
        var expected = new DialogReplyTarget(42L, 77L);

        int updated = "edit".equals(action)
                ? targets.markOperatorMessageEdited(" T-EXACT ", 900L, " after ", expected)
                : targets.markOperatorMessageDeleted(" T-EXACT ", 900L, expected);

        assertThat(updated).isEqualTo(1);
        var sql = org.mockito.ArgumentCaptor.forClass(String.class);
        var args = org.mockito.ArgumentCaptor.forClass(Object[].class);
        verify(jdbc).update(sql.capture(), args.capture());
        assertThat(sql.getValue()).endsWith(" AND user_id = ? AND channel_id = ?");
        assertThat(sql.getValue()).contains("SELECT COUNT(*) FROM tickets unique_ticket",
                "SELECT COUNT(*) FROM chat_history owned");
        if ("edit".equals(action)) {
            assertThat(args.getValue()).containsExactly(" after ", " T-EXACT ", 900L, 42L, 77L);
        } else {
            assertThat(args.getValue()).containsExactly(" T-EXACT ", 900L, 42L, 77L);
        }
        verifyNoInteractions(metadata);
    }

    @ParameterizedTest
    @org.junit.jupiter.params.provider.ValueSource(strings = {"null-target", "null-user", "null-channel"})
    void explicitUnresolvedTargetNeverFallsBackToLegacyWriter(String condition) {
        JdbcTemplate jdbc = mock(JdbcTemplate.class);
        LegacyTicketIdJdbcGuard guard = mock(LegacyTicketIdJdbcGuard.class);
        ChatAttachmentMetadataService metadata = mock(ChatAttachmentMetadataService.class);
        var targets = new DialogReplyTargetService(jdbc, metadata, guard);
        DialogReplyTarget expected = switch (condition) {
            case "null-target" -> null;
            case "null-user" -> new DialogReplyTarget(null, 77L);
            default -> new DialogReplyTarget(42L, null);
        };

        assertThat(targets.markOperatorMessageEdited("T", 900L, "after", expected)).isZero();
        assertThat(targets.markOperatorMessageDeleted("T", 900L, expected)).isZero();
        verifyNoInteractions(jdbc, guard, metadata);
    }
