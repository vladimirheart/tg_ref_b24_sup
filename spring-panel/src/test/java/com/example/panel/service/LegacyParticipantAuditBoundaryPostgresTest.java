package com.example.panel.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.*;

import com.example.panel.config.MultibusinessFeatureFlags;
import com.example.panel.support.PostgresqlJdbcTestSupport;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.stream.Stream;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.jdbc.core.JdbcTemplate;

class LegacyParticipantAuditBoundaryPostgresTest {
    private static final String RAW = " R162/Ю?%#+ ";
    private record Fixture(JdbcTemplate jdbc, MultibusinessFeatureFlags flags, LegacyTicketIdJdbcGuard guard,
                           DialogAuditService service) { }

    private Fixture fixture() {
        var jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplateDefaultStringType("legacy_participant_audit");
        jdbc.execute("""
            CREATE TABLE tickets(user_id BIGINT,ticket_id TEXT,business_id BIGINT,is_general BOOLEAN DEFAULT FALSE,
                PRIMARY KEY(user_id,ticket_id));
            CREATE TABLE dialog_action_audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ticket_id TEXT,actor TEXT,action TEXT,result TEXT,detail TEXT,created_at TIMESTAMPTZ);
            """);
        jdbc.update("INSERT INTO tickets(user_id,ticket_id) VALUES(901,?),(902,?)", RAW, RAW.trim());
        jdbc.update("""
            INSERT INTO dialog_action_audit(ticket_id,actor,action,result,detail,created_at)
            VALUES(?,'original','seed','success','old','2000-01-01T00:00:00Z'),
                  (?,'sibling','seed','success','neighbour','2000-01-01T00:00:00Z')
            """, RAW, RAW.trim());
        var flags = new MultibusinessFeatureFlags();
        var guard = spy(new LegacyTicketIdJdbcGuard(jdbc));
        return new Fixture(jdbc, flags, guard, new DialogAuditService(jdbc, guard, flags));
    }

    private void mutate(Fixture f, String kind) {
        switch (kind) {
            case "business" -> f.jdbc.update("UPDATE tickets SET business_id=7 WHERE ticket_id=?", RAW);
            case "general" -> f.jdbc.update("UPDATE tickets SET is_general=TRUE WHERE ticket_id=?", RAW);
            case "strict" -> f.flags.setStrictReadScope(true);
            case "collision" -> f.jdbc.update("INSERT INTO tickets(user_id,ticket_id) VALUES(903,?)", RAW);
            case "missing" -> f.jdbc.update("DELETE FROM tickets WHERE ticket_id=?", RAW);
            case "schema" -> f.jdbc.execute("ALTER TABLE tickets DROP COLUMN business_id");
            default -> throw new AssertionError(kind);
        }
    }

    static Stream<Arguments> denied() {
        return Stream.of("take", "reassign", "participants_add", "participants_remove")
                .flatMap(action -> Stream.of("business", "general", "strict", "collision", "missing", "schema")
                        .map(kind -> Arguments.of(action, kind)));
    }

    @ParameterizedTest @MethodSource("denied")
    void ownershipAuditCannotAppendToAScopedStrictAmbiguousOrUnknownRoot(String action, String kind) {
        var f = fixture();
        var before = f.jdbc.queryForList("SELECT * FROM dialog_action_audit ORDER BY id");
        mutate(f, kind);
        f.service.logDialogActionAudit(RAW, "actor", " " + action + " ", "success", "new");
        assertThat(f.jdbc.queryForList("SELECT * FROM dialog_action_audit ORDER BY id")).isEqualTo(before);
    }

    static Stream<Arguments> afterProof() {
        return Stream.of("participants_add", "participants_remove").flatMap(action ->
                Stream.of("business", "general", "strict", "collision").map(kind -> Arguments.of(action, kind)));
    }

    @ParameterizedTest @MethodSource("afterProof")
    void successfulEarlyProbeCannotAuthorizeALaterNamespaceOrStrictMode(String action, String kind) {
        var f = fixture();
        var before = f.jdbc.queryForList("SELECT * FROM dialog_action_audit ORDER BY id");
        var once = new AtomicBoolean();
        doAnswer(call -> {
            boolean unique = (boolean) call.callRealMethod();
            if (unique && once.compareAndSet(false, true)) mutate(f, kind);
            return unique;
        }).when(f.guard).hasUniqueTicket(RAW);
        f.service.logDialogActionAudit(RAW, "actor", action, "not_found", "late rejection");
        assertThat(once).isTrue();
        assertThat(f.jdbc.queryForList("SELECT * FROM dialog_action_audit ORDER BY id")).isEqualTo(before);
    }

    static Stream<Arguments> afterBinding() {
        return Stream.of("participants_add", "participants_remove").flatMap(action ->
                Stream.of("business", "general", "collision", "missing").map(kind -> Arguments.of(action, kind)));
    }

    @ParameterizedTest @MethodSource("afterBinding")
    void finalInsertChecksNamespaceAfterSqlArgumentsAreBound(String action, String kind) {
        var f = fixture();
        var before = f.jdbc.queryForList("SELECT * FROM dialog_action_audit ORDER BY id");
        var observed = spy(f.jdbc);
        var once = new AtomicBoolean();
        doAnswer(call -> {
            if (((String) call.getArgument(0)).stripLeading().startsWith("INSERT INTO dialog_action_audit") && once.compareAndSet(false, true)) mutate(f, kind);
            return call.callRealMethod();
        }).when(observed).update(anyString(), any(Object[].class));
        new DialogAuditService(observed, f.guard, f.flags).logDialogActionAudit(RAW, "actor", action, "error", "rejected");
        assertThat(once).isTrue();
        assertThat(f.jdbc.queryForList("SELECT * FROM dialog_action_audit ORDER BY id")).isEqualTo(before);
    }

    @ParameterizedTest @ValueSource(strings = {"take", "reassign", "participants_add", "participants_remove"})
    void unresolvedBeforeStrictPreservesExactIdTrimRulesAndHistoricalRows(String action) {
        var f = fixture();
        var original = f.jdbc.queryForList("SELECT * FROM dialog_action_audit ORDER BY id");
        f.service.logDialogActionAudit(RAW, " Mixed Actor ", " " + action + " ", " success ", " Detail ");
        var row = f.jdbc.queryForMap("SELECT * FROM dialog_action_audit WHERE ticket_id=? AND action=?", RAW, action);
        assertThat(row).containsEntry("ticket_id", RAW).containsEntry("actor", "Mixed Actor")
                .containsEntry("action", action).containsEntry("result", "success").containsEntry("detail", "Detail");
        assertThat(row.get("created_at")).isNotNull();
        assertThat(f.jdbc.queryForList("SELECT * FROM dialog_action_audit WHERE action='seed' ORDER BY id")).isEqualTo(original);
        assertThat(f.jdbc.queryForObject("SELECT count(*) FROM dialog_action_audit WHERE ticket_id=?", Long.class, RAW.trim())).isEqualTo(1L);
    }

    @ParameterizedTest @ValueSource(strings = {"take", "reassign", "participants_add", "participants_remove"})
    void strictOwnershipAuditDoesNotProbeJdbcOrTheLegacyGuard(String action) {
        var jdbc = mock(JdbcTemplate.class);
        var guard = mock(LegacyTicketIdJdbcGuard.class);
        var flags = new MultibusinessFeatureFlags();
        flags.setStrictReadScope(true);
        new DialogAuditService(jdbc, guard, flags).logDialogActionAudit(RAW, "actor", action, "forbidden", "denied");
        verifyNoInteractions(jdbc, guard);
    }

    @ParameterizedTest @ValueSource(strings = {"resolve", "first_response_overdue_notification"})
    void unrelatedAuditAndSuccessfulLookupKeepTheirExistingContract(String action) {
        var f = fixture();
        mutate(f, "business");
        mutate(f, "strict");
        f.service.logDialogActionAudit(RAW, "actor", action, "success", "unchanged");
        assertThat(f.service.hasSuccessfulDialogAction(RAW, action)).isTrue();
        assertThat(f.jdbc.queryForObject("SELECT count(*) FROM dialog_action_audit WHERE ticket_id=? AND action=?", Long.class, RAW, action)).isEqualTo(1L);
    }
}
