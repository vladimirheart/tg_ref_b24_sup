class DialogReplyTargetOwnerProofPostgresqlTest {
    private record Fixture(JdbcTemplate jdbc, LegacyTicketIdJdbcGuard guard,
                           DialogReplyTargetService targets, ChatAttachmentMetadataService metadata) { }

    private Fixture fixture(String owner) {
        JdbcTemplate jdbc = PostgresqlJdbcTestSupport.freshJdbcTemplateDefaultStringType("reply_owner_proof");
        jdbc.execute("CREATE TABLE tickets(user_id BIGINT,ticket_id TEXT,channel_id BIGINT,PRIMARY KEY(user_id,ticket_id))");
        jdbc.execute("CREATE TABLE messages(user_id BIGINT,ticket_id TEXT UNIQUE,channel_id BIGINT,created_at TIMESTAMPTZ)");
        jdbc.execute("""
                CREATE TABLE chat_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT,ticket_id TEXT,channel_id BIGINT,tg_message_id BIGINT,sender TEXT,
                    message TEXT,original_message TEXT,edited_at TIMESTAMPTZ,deleted_at TIMESTAMPTZ,
                    attachment TEXT,message_type TEXT,reply_to_tg_id BIGINT,timestamp TIMESTAMPTZ)
                """);
        jdbc.execute("CREATE TABLE ticket_active(ticket_id TEXT PRIMARY KEY,user_identity TEXT,last_seen TIMESTAMPTZ)");
        jdbc.execute("CREATE TABLE web_form_sessions(ticket_id TEXT)");
        jdbc.update("INSERT INTO tickets VALUES (42,?,77)", owner);
        jdbc.update("INSERT INTO messages VALUES (42,?,77,CURRENT_TIMESTAMP)", owner);
        jdbc.update("""
                INSERT INTO chat_history(user_id,ticket_id,channel_id,tg_message_id,sender,message,message_type)
                VALUES (42,?,77,900,'operator','before','text')
                """, owner);
        if (!owner.equals(owner.trim())) {
            jdbc.update("INSERT INTO tickets VALUES (88,?,88)", owner.trim());
            jdbc.update("INSERT INTO messages VALUES (88,?,88,CURRENT_TIMESTAMP)", owner.trim());
        }
        var guard = spy(new LegacyTicketIdJdbcGuard(jdbc));
        var metadata = mock(ChatAttachmentMetadataService.class);
        return new Fixture(jdbc, guard, new DialogReplyTargetService(jdbc, metadata, guard), metadata);
    }

    private AtomicInteger changeAfterUniqueProof(Fixture fixture, String owner, int proofNumber, Runnable change) {
        var calls = new AtomicInteger();
        doAnswer(call -> {
            boolean unique = (boolean) call.callRealMethod();
            if (calls.incrementAndGet() == proofNumber) {
                assertThat(unique).as("real precheck before committed change").isTrue();
                // Committed before the owner SELECT takes its own statement snapshot.
                change.run();
            }
            return unique;
        }).when(fixture.guard()).hasUniqueTicket(owner);
        return calls;
    }

    private void duplicate(Fixture fixture, String owner, long channelId) {
        fixture.jdbc().update("INSERT INTO tickets VALUES (99,?,?)", owner, channelId);
    }

    static Stream<Arguments> lateDuplicates() {
        return Stream.of("T", " T ").flatMap(owner -> Stream.of(77L, 99L)
                .map(channel -> Arguments.of(owner, channel)));
    }

    @ParameterizedTest
    @MethodSource("lateDuplicates")
    void matchingOwnerCannotAuthorizeALateDuplicate(String owner, long duplicateChannel) {
        Fixture fixture = fixture(owner);
        AtomicInteger calls = changeAfterUniqueProof(fixture, owner, 1,
                () -> duplicate(fixture, owner, duplicateChannel));

        assertThat(fixture.targets().hasReplyTargetOwner(owner, new DialogReplyTarget(42L, 77L))).isFalse();

        assertThat(calls).hasValue(1);
        assertThat(fixture.jdbc().queryForObject(
                "SELECT COUNT(*) FROM tickets WHERE ticket_id=?", Integer.class, owner)).isEqualTo(2);
        verifyNoInteractions(fixture.metadata());
    }

    static Stream<Arguments> replyActions() {
        return Stream.of("T", " T ").flatMap(owner -> Stream.of("text", "media", "edit", "delete")
                .map(action -> Arguments.of(owner, action)));
    }

    @ParameterizedTest
    @MethodSource("replyActions")
    void lateDuplicatePreflightStopsBeforeTransportLedgerOrLocalSideEffects(String owner, String action) {
        Fixture fixture = fixture(owner);
        var historyBefore = fixture.jdbc().queryForList("SELECT * FROM chat_history ORDER BY id");
        AtomicInteger calls = changeAfterUniqueProof(fixture, owner, 2, () -> duplicate(fixture, owner, 99L));
        var transport = mock(DialogReplyTransportService.class);
        var ledger = mock(ProviderDeliveryLedgerService.class);
        var responsibility = mock(DialogResponsibilityService.class);
        Channel channel = new Channel();
        channel.setId(77L); channel.setPlatform("telegram"); channel.setToken("controlled-token");
        when(transport.loadChannel(77L)).thenReturn(Optional.of(channel));
        when(transport.sendText(channel, 42L, "reply", 800L))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(901L, 77L));
        var file = new MockMultipartFile("file", "photo.png", "image/png", new byte[] {1, 2, 3});
        when(transport.sendMedia(channel, 42L, file, "caption", "photo.png", 800L))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(901L, 77L));
        when(transport.editTelegramMessage(channel, 42L, 900L, "after"))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        when(transport.deleteTelegramMessage(channel, 42L, 900L))
                .thenReturn(DialogReplyTransportService.DialogReplyTransportResult.success(900L, 77L));
        var replies = new DialogReplyService(fixture.targets(), transport, responsibility, ledger);
        var resultError = new AtomicReference<String>();

        assertThatNoException().isThrownBy(() -> {
            switch (action) {
                case "text" -> resultError.set(replies.sendReply(owner, "reply", 800L, "operator").error());
                case "media" -> resultError.set(replies.sendMediaReply(owner, file, "caption", 800L, "operator",
                        "stored.png", "photo.png", "image/png", 3L).error());
                case "edit" -> resultError.set(replies.editOperatorMessage(owner, 900L, "after", "operator").error());
                case "delete" -> resultError.set(replies.deleteOperatorMessage(owner, 900L, "operator").error());
                default -> throw new IllegalArgumentException(action);
            }
        });
        assertThat(resultError.get()).isEqualTo("edit".equals(action) || "delete".equals(action)
                ? "Сообщение оператора не найдено." : "Не удалось определить получателя сообщения.");
        verifyNoInteractions(transport, ledger, responsibility, fixture.metadata());
        assertThat(fixture.jdbc().queryForList("SELECT * FROM chat_history ORDER BY id")).isEqualTo(historyBefore);
        assertThat(fixture.jdbc().queryForObject("SELECT COUNT(*) FROM ticket_active", Integer.class)).isZero();
        assertThat(calls).hasValue(2);
    }

    static Stream<Arguments> changedOwners() {
        return Stream.of("T", " T ").flatMap(owner -> Stream.of("missing", "user", "channel", "both")
                .map(change -> Arguments.of(owner, change)));
    }

    @ParameterizedTest
    @MethodSource("changedOwners")
    void missingOrTransferredOwnerStillFailsClosed(String owner, String change) {
        Fixture fixture = fixture(owner);
        AtomicInteger calls = changeAfterUniqueProof(fixture, owner, 1, () -> {
            switch (change) {
                case "missing" -> fixture.jdbc().update("DELETE FROM tickets WHERE ticket_id=?", owner);
                case "user" -> fixture.jdbc().update("UPDATE tickets SET user_id=99 WHERE ticket_id=?", owner);
                case "channel" -> fixture.jdbc().update("UPDATE tickets SET channel_id=99 WHERE ticket_id=?", owner);
                case "both" -> fixture.jdbc().update("UPDATE tickets SET user_id=99,channel_id=99 WHERE ticket_id=?", owner);
                default -> throw new IllegalArgumentException(change);
            }
        });

        assertThat(fixture.targets().hasReplyTargetOwner(owner, new DialogReplyTarget(42L, 77L))).isFalse();

        assertThat(calls).hasValue(1);
        verifyNoInteractions(fixture.metadata());
    }

    @ParameterizedTest
    @ValueSource(strings = {"T", " T ", "T/100", " T/100?&%#+ Ю ", "T%2F+", " null "})
    void exactUniqueOwnerStillRequiresBothUserAndChannel(String owner) {
        Fixture fixture = fixture(owner);

        assertThat(fixture.targets().hasReplyTargetOwner(owner, new DialogReplyTarget(42L, 77L))).isTrue();
        assertThat(fixture.targets().hasReplyTargetOwner(owner, new DialogReplyTarget(99L, 77L))).isFalse();
        assertThat(fixture.targets().hasReplyTargetOwner(owner, new DialogReplyTarget(42L, 99L))).isFalse();
        if (!owner.equals(owner.trim())) {
            assertThat(fixture.targets().hasReplyTargetOwner(owner.trim(), new DialogReplyTarget(42L, 77L))).isFalse();
            assertThat(fixture.targets().hasReplyTargetOwner(owner.trim(), new DialogReplyTarget(88L, 88L))).isTrue();
        }
        verifyNoInteractions(fixture.metadata());
    }

    static Stream<Arguments> invalidTargets() {
        return Stream.of(Arguments.of((Object) null), Arguments.of(new DialogReplyTarget(null, 77L)),
                Arguments.of(new DialogReplyTarget(42L, null)));
    }

    @ParameterizedTest
    @MethodSource("invalidTargets")
    void unresolvedTargetStillStopsBeforeJdbcGuard(DialogReplyTarget target) {
        Fixture fixture = fixture("T");

        assertThat(fixture.targets().hasReplyTargetOwner("T", target)).isFalse();

        verifyNoInteractions(fixture.guard(), fixture.metadata());
    }

    @ParameterizedTest
    @NullSource
    @EmptySource
    @ValueSource(strings = {" ", "missing", " T "})
    void unresolvedExactTicketStillFailsPrecheck(String requested) {
        Fixture fixture = fixture("T");

        assertThat(fixture.targets().hasReplyTargetOwner(requested, new DialogReplyTarget(42L, 77L))).isFalse();

        verifyNoInteractions(fixture.metadata());
    }

    @Test
    void ownerQuerySchemaFailureAfterSuccessfulPrecheckStillReturnsFalse() {
        Fixture fixture = fixture("T");
        AtomicInteger calls = changeAfterUniqueProof(fixture, "T", 1, () -> fixture.jdbc().execute("DROP TABLE tickets"));

        assertThat(fixture.targets().hasReplyTargetOwner("T", new DialogReplyTarget(42L, 77L))).isFalse();

        assertThat(calls).hasValue(1);
        verifyNoInteractions(fixture.metadata());
    }
}
